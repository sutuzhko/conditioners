// ---- Загрузка с fallback на дефолты ----
export function loadData() {
  let stored = null;
  try { stored = JSON.parse(localStorage.getItem(KEY) || 'null'); } catch (e) { stored = null; }
  const base = JSON.parse(JSON.stringify(DEFAULTS));
  if (!stored || typeof stored !== 'object') return base;
  const out = base;
  for (const k of Object.keys(base)) {
    if (stored[k] !== undefined) out[k] = stored[k];
  }
  return out;
}

// ---- Сохранение (вызывает админка; сайт ловит событие storage) ----
export function saveData(data) {
  try { localStorage.setItem(KEY, JSON.stringify(data)); } catch (e) { console.error('saveData:', e); }
}

export const STORAGE_KEY = KEY;

// ---- Утилиты ----
export function fmtPrice(n) {
  return Math.round(+n || 0).toLocaleString('ru-RU') + ' ₽';
}

export function uid(prefix) {
  return (prefix || 'id') + '-' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6);
}

export function today() {
  const d = new Date();
  return d.toISOString().slice(0, 10);
}

export function fmtDate(iso) {
  if (!iso) return '';
  const m = ['января','февраля','марта','апреля','мая','июня','июля','августа','сентября','октября','ноября','декабря'];
  const p = String(iso).split('-');
  if (p.length !== 3) return iso;
  return (+p[2]) + ' ' + m[(+p[1]) - 1] + ' ' + p[0];
}
