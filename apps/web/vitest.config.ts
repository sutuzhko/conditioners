import { defineConfig } from 'vitest/config';
import { loadEnv } from 'vite';
import react from '@vitejs/plugin-react';
import { fileURLToPath } from 'node:url';

export default defineConfig({
  plugins: [react()],
  test: {
    /* 🔴 Переменные окружения тестам даёт среда, а не тест.
       В контейнере их кладёт Compose из `.env.dev`, и полтора десятка файлов
       на этом молча держатся: они импортируют серверный модуль, а тот читает
       `env` на импорте и падает без него ещё до первой проверки. На хосте
       Compose нет — и те же файлы не собирались вовсе, с «Некорректная
       конфигурация окружения: DATABASE_URL Required».

       `loadEnv` читает `.env.local` рядом с приложением — тот самый файл,
       которым живёт хостовый запуск (docs/DEPLOY.md §2). В контейнере файла
       нет, `loadEnv` возвращает пусто, и прогон остаётся ровно таким, каким
       был. */
    env: loadEnv('test', fileURLToPath(new URL('.', import.meta.url)), ''),
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./vitest.setup.ts'],
    // Хеширование argon2 и пережатие через sharp считаются честно и упираются
    // в процессор. При параллельной работе нескольких агентов дефолтные 5 секунд
    // дают ложные падения — тест, падающий от загрузки машины, бесполезен.
    testTimeout: 20_000,
    hookTimeout: 20_000,
    // Vitest по умолчанию занимает все ядра, а рядом в том же контейнере живут
    // dev-сервер и Storybook. На восьми ядрах это давало плавающие падения
    // тестов с таймингом — они проходят изолированно и падают в общем прогоне.
    // Половина ядер надёжнее, чем быстрый, но неверящий себе прогон.
    poolOptions: { threads: { maxThreads: 4, minThreads: 1 } },
    // Проверяемое живёт не только в src: предохранитель демо-сида лежит в
    // prisma/, а регресс на правило слоёв — рядом с конфигом линтера, в корне
    // репозитория. Оба защищают от потерь, которых не видно в диффе, и обязаны
    // попадать в общий прогон, а не запускаться руками.
    include: [
      'src/**/*.{test,spec}.{ts,tsx}',
      'prisma/**/*.{test,spec}.ts',
      '../../scripts/**/*.{test,spec}.mjs',
      // Раннер снимков раскладывает ошибки Playwright по категориям чистой
      // функцией — от неё зависит, красить ли PR (ADR-230). Проверять её нужно
      // без браузера и без витрины, значит здесь, а не в самих снимках.
      'e2e/vr/**/*.test.ts',
    ],
  },
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
});
