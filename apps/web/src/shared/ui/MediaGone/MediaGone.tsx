import styles from './MediaGone.module.css';

export interface MediaGoneProps {
  /**
   * Что случилось: «Фото недоступно». Строка короткая намеренно — та же рамка
   * стоит в плитке 132px, где на длинную не хватит места.
   */
  readonly title: string;
  /**
   * Что делать дальше. Не задано — не рисуется: в мелкой плитке пояснение
   * вытесняет заголовок, а без заголовка рамка перестаёт что-либо сообщать.
   */
  readonly note?: string | undefined;
  /**
   * Геометрия — забота места, а не кита: рамка обязана занять ровно то, что
   * занимала бы картинка, иначе карточка меняет высоту в зависимости от того,
   * дожил файл до сегодня или нет.
   *
   * 🔴 Свойства раздела и кита не пересекаются: здесь рамка, краска и
   * раскладка, снаружи — размеры. Порядок подключения модулей не определён, и
   * общее свойство в двух модулях выигрывал бы то один, то другой.
   *
   * 🔴 В разметке класс раздела идёт **первым** — см. `className` ниже.
   */
  readonly className?: string | undefined;
}

/**
 * Ссылка есть, файла нет (issue #662, #690).
 *
 * 🔴 Не битая картинка и не пустое место, а рамка со словами. Ссылка в базе и
 * файл на томе живут порознь: том переехал, каталог не примонтирован, база
 * наполнена в другом окружении (ADR-326). Без этой рамки панель показывает
 * значок сломанного файла — то есть выглядит сломанной вёрсткой, а не
 * отсутствующим снимком, и владелец идёт чинить не то.
 *
 * 🔴 `<img>` при этом не создаётся вовсе. Приём в том и состоит: узнать, что
 * файла нет, обязан сервер, а разметка приходит уже верной (инвариант 1).
 * Ветка `onError` в браузере сначала показала бы значок битого файла и только
 * потом убрала его — с прыжком раскладки.
 *
 * 🔴 Пунктир, а не сплошная рамка со значком камеры. «Фотографии нет вовсе» —
 * другое состояние, и рисуется оно иначе (значок камеры в сплошной рамке, как
 * в списке каталога): ответы на экране у них разные, потому что разные и
 * действия — одно заводится загрузкой, другое поиском пропавшего файла
 * (ADR-361).
 *
 * ---
 *
 * 🔴 **Почему это не вариант `EmptyState` — разобрано по issue #877.**
 *
 * Вопрос законный: анатомия похожа — рамка, заголовок, необязательное
 * пояснение, — и седьмой сосед в ките с той же анатомией был бы ровно тем, на
 * что владелец жалуется. Ответ «нет», и держится он на четырёх различиях, три
 * из которых проверяются числом или разметкой, а не вкусом.
 *
 * 1. **Разное место в дереве доступности, и это не косметика.** `EmptyState` и
 *    `ErrorState` — состояния **раздела**: они стоят вместо списка и намеренно
 *    рисуют `<h2>`, потому что обход по заголовкам обязан на пустом разделе
 *    останавливаться. Эта плашка стоит **внутри** карточки и повторяется по
 *    числу снимков: в галерее наряда их шесть в ряд. Шесть `<h2>` подряд
 *    внутри одной карточки ломают структуру заголовков (инвариант 4) и
 *    превращают обход озвучкой в перечисление одинаковых «Фото недоступно».
 *    Замена одной картинки — это `role="note"`, а не остановка обхода.
 *    Различие держится проверками: `MediaGone.test.tsx` требует, чтобы
 *    заголовка здесь не было, `EmptyState.test.tsx` — чтобы он там был.
 *
 * 2. **Геометрия `EmptyState` не помещается в самое тесное место.** Его
 *    собственная коробка — поля 28px сверху и снизу, круг значка 48px и
 *    отбивка 12px — это 116px по вертикали **до первой буквы**, а с заголовком
 *    `--fs-h3` под 140. Самая мелкая плашка стоит в карточке клиента и равна
 *    **96×96** (`ClientUnits.module.css`), в сдаче наряда — 100×100. Размеры
 *    здесь задаёт раздел, а `EmptyState` держит свои: чтобы он влез, снаружи
 *    пришлось бы переопределить и поля, и значок, и кегль заголовка — то есть
 *    завести те же свойства в двух модулях, порядок подключения которых не
 *    определён. Ровно этого пересечения модуль ниже и избегает.
 *
 * 3. **Обязательное у `EmptyState` здесь отсутствует, и не по недосмотру.**
 *    Значок и пояснение (`children`) у него обязательны сознательно: пустой
 *    раздел без причины читается как поломка. В плитке 96×96 пояснение
 *    вытесняет заголовок, а значка нет вовсе. Сделать оба необязательными —
 *    значит завести у `EmptyState` состояние «без значка, без текста,
 *    пунктиром», которым ни один раздел пользоваться не должен, и вернуть тот
 *    же вопрос выбора уже внутрь разделов.
 *
 * 4. **Разный смысл рамки** — пунктир против сплошной, см. абзац выше.
 *
 * Отвергнуто: `EmptyState` с пропом размера (`size="tile"`), у которого значок
 * и пояснение необязательны. Он снимает доводы 2 и 3, но не первый: заголовок
 * либо остаётся и ломает структуру, либо исчезает — и тогда `EmptyState`
 * перестаёт быть остановкой обхода в том самом случае, ради которого он
 * заведён. Компонент, у которого от значения пропа меняется роль в дереве
 * доступности, — это два компонента с общим именем.
 */
export function MediaGone({ title, note, className }: MediaGoneProps) {
  /* 🔴 Класс раздела идёт первым, китовый — вторым, как у строки таблицы
     (`Table/TableRow.tsx`). Порядок здесь не про CSS, где он не значит
     ничего, а про измерения раскладки (ADR-234): узел в снимке называется
     **первым** классом-модулем (`e2e/vr/measurements/collect.ts`). Поставь
     китовый класс вперёд — и плашка во всех шести разделах станет в диффе
     одинаковым безымянным `div.MediaGone__box`, а правка размера в одном
     разделе прочитается как правка общего узла. */
  return (
    <div className={[className, styles.box].filter(Boolean).join(' ')} role="note">
      <span className={styles.title}>{title}</span>
      {note === undefined ? null : <span className={styles.note}>{note}</span>}
    </div>
  );
}
