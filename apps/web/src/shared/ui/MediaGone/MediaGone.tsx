import styles from './MediaGone.module.css';

export interface MediaGoneProps {
  /**
   * Что случилось: «Фото недоступно». Строка короткая намеренно — та же рамка
   * стоит в плитке 132px, где на длинную не хватит места.
   */
  readonly title: string;
  /**
   * Что делать дальше. Не задано — не рисуется: в мелкой плитке пояснение
   * вытесняет заголовок, а без заголовка рамка перестаёт что-либо сообщать.
   */
  readonly note?: string | undefined;
  /**
   * Геометрия — забота места, а не кита: рамка обязана занять ровно то, что
   * занимала бы картинка, иначе карточка меняет высоту в зависимости от того,
   * дожил файл до сегодня или нет.
   *
   * 🔴 Свойства раздела и кита не пересекаются: здесь рамка, краска и
   * раскладка, снаружи — размеры. Порядок подключения модулей не определён, и
   * общее свойство в двух модулях выигрывал бы то один, то другой.
   *
   * 🔴 В разметке класс раздела идёт **первым** — см. `className` ниже.
   */
  readonly className?: string | undefined;
}

/**
 * Ссылка есть, файла нет (issue #662, #690).
 *
 * 🔴 Не битая картинка и не пустое место, а рамка со словами. Ссылка в базе и
 * файл на томе живут порознь: том переехал, каталог не примонтирован, база
 * наполнена в другом окружении (ADR-326). Без этой рамки панель показывает
 * значок сломанного файла — то есть выглядит сломанной вёрсткой, а не
 * отсутствующим снимком, и владелец идёт чинить не то.
 *
 * 🔴 `<img>` при этом не создаётся вовсе. Приём в том и состоит: узнать, что
 * файла нет, обязан сервер, а разметка приходит уже верной (инвариант 1).
 * Ветка `onError` в браузере сначала показала бы значок битого файла и только
 * потом убрала его — с прыжком раскладки.
 *
 * 🔴 Пунктир, а не сплошная рамка со значком камеры. «Фотографии нет вовсе» —
 * другое состояние, и рисуется оно иначе (значок камеры в сплошной рамке, как
 * в списке каталога): ответы на экране у них разные, потому что разные и
 * действия — одно заводится загрузкой, другое поиском пропавшего файла.
 */
export function MediaGone({ title, note, className }: MediaGoneProps) {
  /* 🔴 Класс раздела идёт первым, китовый — вторым, как у строки таблицы
     (`Table/TableRow.tsx`). Порядок здесь не про CSS, где он не значит
     ничего, а про измерения раскладки (ADR-234): узел в снимке называется
     **первым** классом-модулем (`e2e/vr/measurements/collect.ts`). Поставь
     китовый класс вперёд — и плашка во всех шести разделах станет в диффе
     одинаковым безымянным `div.MediaGone__box`, а правка размера в одном
     разделе прочитается как правка общего узла. */
  return (
    <div className={[className, styles.box].filter(Boolean).join(' ')} role="note">
      <span className={styles.title}>{title}</span>
      {note === undefined ? null : <span className={styles.note}>{note}</span>}
    </div>
  );
}
