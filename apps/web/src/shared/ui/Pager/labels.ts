/**
 * Подписи разбивки по умолчанию.
 *
 * 🔴 Отдельным модулем, а не значениями по умолчанию внутри компонента. Те же
 * строки читает сквозной сценарий, и переписанные там руками они разошлись
 * молча: когда шаг в панели стал шевроном с именем «Следующая страница»
 * (issue #748), три сценария `content-paging` продолжали пятнадцать секунд
 * искать ссылку «Дальше →», которой в разметке больше нет. Падение выглядело
 * дефектом кода, а было вторым источником правды об одной строке.
 *
 * Модуль намеренно пустой от React, стилей и любых импортов: Playwright
 * подтягивает его так же, как `content.ts` разделов, и тянуть за собой
 * компонент с CSS-модулем ему нельзя.
 */
export const pagerLabels = {
  /** Имя ряда разбивки, когда раздел не задал своё. */
  nav: 'Страницы списка',

  /**
   * Видимые слова шага — контур витрины: там разбивка стоит под каталогом на
   * длинной странице и читается текстом, а не сеткой номеров.
   */
  prev: 'Назад',
  next: 'Дальше',

  /**
   * Имя шага в полосе номеров — контур панели. Шаг там нарисован шевроном по
   * макету (`.pg`, `design/admin/_base.css`), и имя обязано называть, **куда**
   * ведёт ссылка: «‹» само по себе не имя, а «Назад» рядом с номерами страниц
   * читается как «вернуться в раздел».
   */
  prevPage: 'Предыдущая страница',
  nextPage: 'Следующая страница',

  /** Имя ссылки на страницу: «3» в озвучке само по себе ничего не значит. */
  page: (target: number): string => `Страница ${target}`,

  /** Подпись положения в ряду: её видно, и вокруг неё два шага. */
  position: (current: number, total: number): string => `${current} из ${total}`,

  /**
   * Что читалка слышит после перехода.
   *
   * 🔴 Словами, а не цифрами, и отдельно от `position`. Объявление звучит без
   * ряда вокруг и в момент, когда на экране не шевельнулось ничто, — оно
   * обязано сказать, что именно произошло.
   */
  announce: (current: number, total: number): string => `Показана страница ${current} из ${total}`,
} as const;
