'use client';

import type { RefObject } from 'react';
import { useLayoutEffect } from 'react';

/**
 * Куда встал слой: координаты от края окна, в пикселях. Горизонталь задаётся
 * одной стороной — меню держится правым краем кнопки, подсказка левым краем
 * пузырька, — вторая остаётся пустой.
 */
export interface LayerPlacement {
  readonly top: number;
  readonly left?: number | undefined;
  readonly right?: number | undefined;
}

export interface AnchoredLayer<L extends HTMLElement> {
  /** Открыт ли слой: пока закрыт, ничего не измеряется и кадры не считаются. */
  readonly open: boolean;
  /** Сам всплывающий слой — узел, которому хук пишет координаты. */
  readonly layerRef: RefObject<L | null>;
  /**
   * Счёт положения — чистая функция от геометрии якоря и слоя.
   *
   * 🔴 Обязана быть стабильной (`useCallback`): она стоит в зависимостях
   * эффекта, и новая ссылка на каждый кадр перезапускала бы наблюдение.
   */
  readonly measure: () => LayerPlacement | null;
}

/**
 * Положение всплывающего слоя, который стоит у своего якоря (ADR-328).
 *
 * Общее у меню строки и подсказки: оба лежат `position: fixed` в портале и
 * считают координаты от элемента, рядом с которым обязаны стоять. Разное —
 * только сама формула, и она остаётся у вызывающего.
 *
 * 🔴 Положение считается заново перед каждым кадром, пока слой открыт, и
 * пишется прямо в узел. Причина — issue #683: якорь умеет **переехать, не
 * изменившись в размере**, и тогда ни одно событие не наступает вовсе.
 * Замерено на витрине: таблица стилей витрины доезжала после первого кадра,
 * `#storybook-root` получал `padding: 1rem`, кнопка уезжала с (1392,16) на
 * (1376,32) — те же 32×32, — и меню оставалось стоять по старому замеру, на
 * 16px выше и на 16px правее своей кнопки. Прокрутки нет, размера окна никто
 * не менял, `ResizeObserver` молчит: он смотрит на размер, а переехало
 * положение. Так красились случайные кадры на семи чужих ветках подряд.
 *
 * Перебор способов узнать о переезде (прокрутка, размер окна, размер якоря,
 * `document.fonts.ready`) закрывал по одной причине за раз и каждый раз
 * оставлял следующую. Кадр закрывает их все сразу: что бы ни сдвинуло якорь,
 * до отрисовки слой уже стоит на новом месте.
 *
 * Цена замерена, а не оценена: замер и запись стоят 1.5 мкс, при 60 кадрах в
 * секунду это 0.09 мс — девять тысячных процента кадрового бюджета, и платится
 * оно только пока слой открыт.
 *
 * 🔴 Координаты идут мимо состояния React. Через состояние они дают лишний
 * проход отрисовки на каждое движение, а главное — попадают в кадр на такт
 * позже: перерисовка по `setState` из `requestAnimationFrame` планируется, а
 * не выполняется на месте. Запись в узел происходит внутри того же кадра, до
 * отрисовки, поэтому неверного кадра не бывает ни одного — включая первый:
 * первый счёт идёт в `useLayoutEffect`, то есть до первой отрисовки слоя.
 */
export function useAnchoredLayer<L extends HTMLElement>({
  open,
  layerRef,
  measure,
}: AnchoredLayer<L>): void {
  useLayoutEffect(() => {
    if (!open) return undefined;

    let frame = 0;
    /* Последнее записанное положение строкой: запись того же значения всё
       равно пометила бы стиль изменённым и заставляла бы пересчитывать
       раскладку каждый кадр. */
    let written = '';

    const place = (): void => {
      frame = requestAnimationFrame(place);

      const layer = layerRef.current;
      if (layer === null) return;

      const at = measure();
      if (at === null) {
        /* Не измерено — не показываем: кадр в левом верхнем углу успевает
           попасть на экран и читается как поломка. Прозрачность, а не
           `visibility`, — скрытый ею элемент не принимает фокус, а меню
           забирает фокус себе в этом же кадре. */
        layer.style.opacity = '0';
        return;
      }

      const next = `${at.top}|${at.left ?? ''}|${at.right ?? ''}`;
      if (next === written) return;
      written = next;

      layer.style.top = `${at.top}px`;
      layer.style.left = at.left === undefined ? '' : `${at.left}px`;
      layer.style.right = at.right === undefined ? '' : `${at.right}px`;
      layer.style.opacity = '';
    };

    place();

    return () => cancelAnimationFrame(frame);
  }, [open, measure, layerRef]);
}
