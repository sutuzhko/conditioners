/**
 * Яндекс.Метрика: цели и защита форм от Вебвизора (ADR-024, docs/SEO.md §6).
 *
 * Счётчик — единственный сторонний скрипт на сайте. Всё, что о нём знает
 * остальной код, лежит здесь.
 */

/**
 * Имена целей.
 *
 * 🔴 Одним списком, а не строками по месту вызова. Имя цели стоит
 * одновременно в коде и в интерфейсе Метрики: опечатка в одном из двух мест
 * даёт цель, которая не срабатывает никогда и молча — отчёт просто
 * показывает ноль, и понять, сломан код или никто не оставлял заявок,
 * невозможно.
 */
export const METRIKA_GOALS = {
  /** Заявка ушла на сервер и принята (инвариант 2 — запись в БД уже есть). */
  lead: 'lead_sent',
  /** Отзыв отправлен на модерацию. */
  review: 'review_sent',
  /** Нажатие на телефон — на любой странице и в любом блоке. */
  phone: 'phone_click',
  /** Человек тронул калькулятор монтажа: считается один раз за визит блока. */
  calculator: 'calculator_used',
} as const;

export type MetrikaGoal = (typeof METRIKA_GOALS)[keyof typeof METRIKA_GOALS];

declare global {
  interface Window {
    /**
     * Ставится встроенным скриптом счётчика. Номер счётчика знает только он,
     * и повторять номер в каждом вызове цели не нужно: счётчик не подключён —
     * функции нет, и вызовы ничего не делают.
     */
    ymGoal?: (goal: string) => void;
  }
}

/**
 * Отметить цель. Безопасно везде: на сервере, до загрузки счётчика и когда
 * счётчик не подключён вовсе — ни исключения, ни ветвления на месте вызова.
 */
export function reachGoal(goal: MetrikaGoal): void {
  if (typeof window === 'undefined') return;
  window.ymGoal?.(goal);
}

/**
 * 🔴 Метки Вебвизора для полей с персональными данными (инвариант 12, 152-ФЗ).
 *
 * `ym-disable-keys` запрещает записывать нажатия клавиш, `ym-hide-content` —
 * содержимое поля. Ставятся **разметкой**, а не переключателем в интерфейсе
 * Метрики: переключатель однажды сдвинут — и имя с телефоном уезжают в запись
 * сессии, о чём никто не узнает. Разметка уезжает вместе с формой и живёт
 * ровно столько, сколько живёт поле.
 *
 * Классы глобальные и без стилей: это метки для чужого скрипта, а не
 * оформление, — поэтому им не место в CSS-модуле.
 */
export const YM_MASK = 'ym-disable-keys ym-hide-content';
