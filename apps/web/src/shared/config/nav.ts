import type { ButtonLinkHref } from '@/shared/ui';

/**
 * Пункт навигации. Тип живёт рядом с картой навигации, а не в шапке: слой
 * shared не может импортировать виджеты (ADR-096), и это карта диктует
 * шапке форму пункта, а не наоборот. Адрес типизирован так же, как у
 * next/link: при включённых typedRoutes опечатка в маршруте ловится
 * компилятором на стороне страницы.
 */
export type NavItem = {
  readonly label: string;
  readonly href: ButtonLinkHref;
  /** активный раздел — на него ставится aria-current="page" */
  readonly current?: boolean | undefined;
};

/**
 * Навигация сайта. Здесь перечислено только то, что на сайте действительно
 * есть: ссылка на несуществующий маршрут или якорь — это мёртвая ссылка,
 * которую видят и посетитель, и робот. Пункты добавляются по мере готовности.
 *
 * Сайт — лендинг (ADR-049): разделы — это секции главной, и навигация ведёт
 * на их якоря. Форма `/#якорь`, а не `#якорь`, — те же ссылки стоят в шапке
 * страниц статей и политики, где голый якорь вёл бы в никуда.
 *
 * 🔴 Порядок пунктов повторяет порядок секций на странице. Меню лендинга —
 * это оглавление: человек, читающий его сверху вниз, должен понимать, что
 * ниже по странице, а адрес в строке браузера меняется вслед за прокруткой
 * (ADR-053) и обязан идти в ту же сторону, что и меню.
 */
export const SITE_NAV: readonly NavItem[] = [
  { label: 'Каталог', href: '/#catalog' },
  { label: 'Монтаж', href: '/#installation' },
  { label: 'Цены', href: '/#prices' },
  { label: 'Сервис', href: '/#service' },
  { label: 'Отзывы', href: '/#reviews' },
  /* На секцию лендинга, а не на страницу: увести из середины воронки на
     листинг статей — потерять человека, который до неё дочитал. Кнопка «все
     статьи» внутри секции ведёт на `/knowledge` тем, кому нужен архив. */
  { label: 'База знаний', href: '/#knowledge' },
  { label: 'Контакты', href: '/#contacts' },
];

