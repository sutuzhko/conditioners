/**
 * Единицы измерения склада: набор задаёт код, номенклатуру — владелец
 * (инвариант 8, ADR-134).
 *
 * 🔴 Словарь живёт в `shared`, а не в фиче, потому что читателей у него трое:
 * раздел склада, карточка наряда и текст уведомления. Слой `server` не имеет
 * права импортировать интерфейсные слои, импорт вбок между слайсами одного
 * слоя запрещён — общее уходит вниз. Три копии уже разошлись однажды:
 * «бухт.», «бухт» и «бухта».
 */
export const STOCK_UNITS = [
  'piece',
  'meter',
  'kilogram',
  'liter',
  'pair',
  'pack',
  'coil',
  'roll',
  'cylinder',
] as const;

export type StockUnit = (typeof STOCK_UNITS)[number];

/**
 * 🔴 Сокращения, а не слова, и причина не в экономии места. Остаток дробный:
 * «0,5 баллона», «2 баллона», «5 баллонов» — три формы одного слова, и
 * `plural` их не даст, потому что дробное число он разбирает как целое.
 * «2 баллон» на экране владельца выглядит поломкой системы, а не опечаткой.
 * Сокращение не склоняется вовсе — и остаётся верным при любом числе.
 */
export const STOCK_UNIT_SHORT: Readonly<Record<StockUnit, string>> = {
  piece: 'шт.',
  meter: 'м',
  kilogram: 'кг',
  liter: 'л',
  pair: 'пар.',
  pack: 'уп.',
  coil: 'бух.',
  roll: 'мот.',
  cylinder: 'бал.',
};
