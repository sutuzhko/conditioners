/**
 * Предел размера загружаемого фото — один на проект.
 *
 * 🔴 Значение записано в контракте (docs/API.md §7, «≤ 5 МБ») и проверяется на
 * сервере. Клиент обязан брать его отсюда же: когда поле пускало 8 МБ, а сервер
 * принимал 5, человек прикладывал фото, ждал отправки и получал `413` уже после
 * неё — на мобильном интернете это ещё и впустую потраченный трафик. Подсказка
 * обязана приходить до отправки.
 *
 * Значение по умолчанию для `UPLOAD_MAX_BYTES` берётся отсюда же, поэтому
 * поднять предел можно только осознанно — правкой переменной окружения вместе
 * с контрактом, а не расхождением двух чисел в коде.
 */

export const BYTES_IN_MB = 1024 * 1024;

export const UPLOAD_MAX_BYTES = 5 * BYTES_IN_MB;

/** То же число для микрокопии: «до 5 МБ». */
export const UPLOAD_MAX_MB = UPLOAD_MAX_BYTES / BYTES_IN_MB;
