/**
 * Очереди, число которых панель показывает у пункта навигации (ADR-309).
 *
 * 🔴 Тип лежит в `shared`, а не в оболочке и не в сервисе: его называют оба —
 * сервер считает числа, оболочка их рисует, — а импортировать друг у друга им
 * запрещает правило слоёв. Второй такой же тип рядом разошёлся бы с первым на
 * первой же добавленной очереди.
 *
 * Ключ — очередь, а не адрес раздела: адрес принадлежит навигации и меняется
 * вместе с ней, а «сколько нарядов в работе» от адреса не зависит.
 */
export type AdminCounterKey = 'orders' | 'leads' | 'reviews';

/**
 * Сколько ждёт внимания в каждой очереди.
 *
 * Отсутствующий ключ означает «счётчика у этого пункта нет» — это не то же
 * самое, что ноль: ноль владелец видит и радуется, а монтажнику чужая очередь
 * не показывается вовсе.
 */
export type AdminCounts = Readonly<Partial<Record<AdminCounterKey, number>>>;
