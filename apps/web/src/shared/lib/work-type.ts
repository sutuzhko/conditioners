import { z } from 'zod';

import type { IconName } from '@/shared/ui';

/**
 * Вид работ — одно понятие на заявку, календарь и наряд (ADR-343).
 *
 * 🔴 Перечня видов здесь нет и не будет: «Монтаж», «Замер» и «Чистка дренажа»
 * — данные владельца, а не константы кода (инвариант 8). Модуль описывает
 * только форму записи справочника и палитру, из которой владелец выбирает
 * краску.
 *
 * 🔴 Лежит в `shared`, а не в своём слайсе `entities`, по той же причине, что
 * и словарь причин отказа (ADR-311): вид работ нужен сразу трём сущностям —
 * обращению, делу календаря и наряду, — а импорт вбок между слайсами одного
 * слоя запрещён. Пока вид работ был только у дела, модель жила в
 * `entities/work-type`; с переездом наряда (фаза 2) её понадобилось видеть и
 * из `entities/order`, и выбор стал ровно тот же: либо словарь в `shared`,
 * либо вторая копия формы записи.
 */

/**
 * Краски справочника — ключи палитры, а не цвета.
 *
 * 🔴 Владелец выбирает из готового набора, а не из колеса цветов (ADR-343).
 * Причина не в удобстве: тёмная тема в проекте делается переопределением
 * значений токенов, и записанный цвет не умеет меняться вместе с ней —
 * краска, читаемая на белом, на тёмном фоне даёт серое на сером. Каждая
 * краска здесь — пара токенов «фон + текст», проверенная в обеих темах
 * (`palette.test.ts`).
 *
 * Набор растёт только вместе с токенами, то есть правкой кода: новой краске
 * нужны и значения, и проверка контраста. Поэтому он и ограничен здесь, а не
 * в панели.
 */
export const workTypeToneSchema = z.enum([
  'accent',
  'info',
  'ok',
  'warn',
  'sale',
  'error',
  'neutral',
]);

export type WorkTypeTone = z.infer<typeof workTypeToneSchema>;

export const WORK_TYPE_TONES: readonly WorkTypeTone[] = workTypeToneSchema.options;

/**
 * Вид работ в том виде, в каком его показывают: подпись, значок и краска.
 *
 * Ровно то, что нужно метке в сетке календаря, строке в списке и полю выбора
 * в форме. Признаки «предлагать на сайте» и «активен» решают, попадёт ли вид
 * в список, — самому виду в разметке они не нужны.
 */
export type WorkTypeMark = {
  readonly id: string;
  /** Адресуемый ключ: он уедет в параметр формы заявки (инвариант 17). */
  readonly code: string;
  readonly title: string;
  readonly icon: IconName;
  readonly tone: WorkTypeTone;
  /**
   * Дело этого вида занимает день целиком, а не час: «Заметка» висит на дне
   * и живёт в полосе «Весь день».
   *
   * 🔴 Признак справочника, а не правило в коде. До ADR-343 это решала строка
   * `item.tone === 'note'` в раскладке календаря — последний вид работ,
   * зашитый в код: переименуй владелец «Заметку», и заметки уехали бы на
   * часовую сетку молча.
   */
  readonly dayLong: boolean;
};

/**
 * Вид работ в списке выбора.
 *
 * 🔴 Отключённый вид работ остаётся у прежних записей (ADR-343): отключение —
 * это то, что владелец делает вместо удаления, и удаление занятого вида
 * запрещено именно затем. Но список выбора собирается из активных, и наряд с
 * отключённым видом открывался бы на правку с пустым обязательным полем —
 * владелец видел бы «вид работ не заполнен» там, где он заполнен, и перезаписал
 * бы его первым попавшимся.
 *
 * Поэтому запись самой карточки подмешивается в список и помечается: она
 * видна как выбранная, но выбрать её заново нельзя.
 */
export type WorkTypeOption = WorkTypeMark & { readonly active: boolean };

/**
 * Список выбора: активные виды работ плюс те, что стоят у показываемых
 * записей.
 *
 * Чистая функция, а не второй запрос: запись привозит свой вид работ целиком
 * (`WorkTypeMark`), и узнавать в базе то, что уже в руках, незачем.
 * Отключённым считается всё, чего нет в активном списке, — по построению, а не
 * по колонке: другого способа попасть сюда у вида работ нет.
 */
export function workTypeOptions(
  active: readonly WorkTypeMark[],
  used: readonly WorkTypeMark[],
): readonly WorkTypeOption[] {
  const options: WorkTypeOption[] = active.map((workType) => ({ ...workType, active: true }));
  const known = new Set(options.map((workType) => workType.id));

  for (const workType of used) {
    if (known.has(workType.id)) continue;

    known.add(workType.id);
    options.push({ ...workType, active: false });
  }

  return options;
}
