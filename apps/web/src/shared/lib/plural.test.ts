import { describe, expect, it } from 'vitest';

import { plural, pluralize } from './plural';

describe('склонение после числа', () => {
  it('единственное число — только на «один»', () => {
    expect(plural(1, 'обращение', 'обращения', 'обращений')).toBe('обращение');
    expect(plural(21, 'обращение', 'обращения', 'обращений')).toBe('обращение');
    expect(plural(101, 'обращение', 'обращения', 'обращений')).toBe('обращение');
  });

  it('малое множественное — на 2, 3, 4', () => {
    expect(plural(2, 'обращение', 'обращения', 'обращений')).toBe('обращения');
    expect(plural(34, 'обращение', 'обращения', 'обращений')).toBe('обращения');
  });

  it('🔴 подростковые числа — исключение, на котором ломались самодельные правила', () => {
    expect(plural(11, 'обращение', 'обращения', 'обращений')).toBe('обращений');
    expect(plural(12, 'обращение', 'обращения', 'обращений')).toBe('обращений');
    expect(plural(14, 'обращение', 'обращения', 'обращений')).toBe('обращений');
    expect(plural(111, 'обращение', 'обращения', 'обращений')).toBe('обращений');
  });

  it('ноль и круглые десятки — множественное', () => {
    expect(plural(0, 'обращение', 'обращения', 'обращений')).toBe('обращений');
    expect(plural(10, 'обращение', 'обращения', 'обращений')).toBe('обращений');
    expect(plural(25, 'обращение', 'обращения', 'обращений')).toBe('обращений');
  });

  it('pluralize склеивает число со словом', () => {
    expect(pluralize(3, 'характеристика', 'характеристики', 'характеристик')).toBe(
      '3 характеристики',
    );
  });
});
