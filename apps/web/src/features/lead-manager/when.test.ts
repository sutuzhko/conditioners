import { describe, expect, it } from 'vitest';

import { leadIsStale, leadWaiting } from './when';

/**
 * Относительное время очереди (issue #601). Раздел заявок открывают ради
 * одного вопроса — кому звонить первым, — и абсолютная дата отвечает на него
 * вычитанием в уме.
 *
 * Пояс работ — московский (ADR-080): «вчера» здесь вчера по Москве, даже если
 * панель открыли из другого часового пояса.
 */
const now = new Date('2026-08-30T11:19:00.000Z'); // 14:19 по Москве

describe('сколько обращение ждёт', () => {
  it('первая минута — «только что», а не «0 минут назад»', () => {
    expect(leadWaiting('2026-08-30T11:18:30.000Z', now)).toBe('только что');
  });

  it('минуты склоняются', () => {
    expect(leadWaiting('2026-08-30T11:18:00.000Z', now)).toBe('1 минуту назад');
    expect(leadWaiting('2026-08-30T11:16:00.000Z', now)).toBe('3 минуты назад');
    expect(leadWaiting('2026-08-30T10:40:00.000Z', now)).toBe('39 минут назад');
  });

  it('часы склоняются', () => {
    expect(leadWaiting('2026-08-30T10:19:00.000Z', now)).toBe('1 час назад');
    expect(leadWaiting('2026-08-30T09:19:00.000Z', now)).toBe('2 часа назад');
    expect(leadWaiting('2026-08-30T06:19:00.000Z', now)).toBe('5 часов назад');
  });

  /* 🔴 За границей суток человек мыслит днями, и точное время говорит
     больше: по нему видно, звонили ли уже. */
  it('вчерашнее называется днём и временем', () => {
    expect(leadWaiting('2026-08-29T08:20:00.000Z', now)).toBe('вчера, 11:20');
  });

  it('старое — датой', () => {
    expect(leadWaiting('2026-08-27T08:20:00.000Z', now)).toBe('27 авг');
  });

  /* 🔴 Граница суток считается по Москве, а не по UTC: обращение, пришедшее
     в 23:30 по Москве, для сервера в UTC ещё вчерашнее. */
  it('🔴 сутки считаются в поясе работ, а не в поясе сервера', () => {
    // 30 августа 00:30 по Москве — это 29 августа 21:30 UTC
    const midnight = new Date('2026-08-29T21:30:00.000Z');

    // семь часов назад по московскому календарю — тот же день
    expect(leadWaiting('2026-08-29T21:00:00.000Z', midnight)).toBe('30 минут назад');
    // а это уже вчера по Москве, хотя по UTC — тот же день
    expect(leadWaiting('2026-08-29T18:00:00.000Z', midnight)).toBe('вчера, 21:00');
  });

  /* Часы стенда и часы браузера расходятся: «через три минуты» в очереди
     бессмысленно — заявка уже пришла. */
  it('время из будущего не показывается будущим', () => {
    expect(leadWaiting('2026-08-30T11:25:00.000Z', now)).toBe('только что');
  });
});

describe('залежавшееся обращение', () => {
  it('сутки — граница, после которой обращение считается залежавшимся', () => {
    expect(leadIsStale('2026-08-29T11:19:00.000Z', now)).toBe(true);
    expect(leadIsStale('2026-08-29T11:20:00.000Z', now)).toBe(false);
  });
});
