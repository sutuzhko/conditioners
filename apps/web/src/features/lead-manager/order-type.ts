/**
 * Тип работ по теме обращения (CRM.md §3.4).
 *
 * 🔴 Чистая функция с тестами, а не `if` в карточке заявки: тему пишет
 * человек, набор правил будет расти, а угадывание, живущее в разметке, нельзя
 * ни проверить, ни повторить.
 *
 * 🔴 Угадывание осторожное. Порядок разбора — монтаж, ремонт, обслуживание, и
 * это не алфавит: когда в теме есть и монтаж, и что-то ещё («установка после
 * ремонта»), выигрывает монтаж. Он же остаётся, когда не совпало ничего:
 * ошибиться в сторону монтажа дешевле всего — это самый частый вид работ, и
 * владелец правит тип в форме одним щелчком, пока наряд ещё черновик.
 */
import type { OrderType } from '@/entities/order/model';

/**
 * Тема приводится к нижнему регистру, «ё» — к «е»: «течёт» и «течет» пишут
 * поровну, а два варианта каждого слова в списке разошлись бы на первой правке.
 */
function normalize(topic: string): string {
  return topic.toLowerCase().replaceAll('ё', 'е');
}

/** Монтаж: «демонтаж» и «переустановка» ловятся теми же корнями. */
const INSTALL_MARKS: readonly string[] = ['монтаж', 'установ', 'устанавл', 'подключ'];

/** Поломка. Список тесный: сюда попадают только однозначные слова. */
const REPAIR_MARKS: readonly string[] = [
  'ремонт',
  'почин',
  'слома',
  'не работает',
  'не включ',
  'не охлажд',
  'не морозит',
  'не холодит',
  'не греет',
  'течет',
  'протеч',
  'протека',
  'неисправ',
  'диагностик',
  'авари',
];

/** Обслуживание: плановые работы на исправной технике. */
const SERVICE_MARKS: readonly string[] = [
  'чистк',
  'обслуж',
  'профилакт',
  'заправ',
  'промывк',
  'антибактер',
];

/**
 * «ТО» ищется в исходной теме заглавными и по границам слова.
 *
 * Строчное «то» — обычный союз: «что-то не так с кондиционером» иначе стало бы
 * плановым обслуживанием. Границы нужны против «АВТО» и «ТОЧКА»; `\b` здесь не
 * годится — для регулярных выражений JavaScript кириллица не буква.
 */
const MAINTENANCE_ABBR = /(^|[^A-Za-zА-Яа-яЁё0-9])ТО([^A-Za-zА-Яа-яЁё0-9]|$)/;

function hasAny(text: string, marks: readonly string[]): boolean {
  return marks.some((mark) => text.includes(mark));
}

/**
 * Какой наряд заводить по обращению. Тема пустая или незнакомая — монтаж.
 */
export function guessOrderType(topic: string | null | undefined): OrderType {
  const text = normalize(topic ?? '');

  if (hasAny(text, INSTALL_MARKS)) return 'install';
  if (hasAny(text, REPAIR_MARKS)) return 'repair';
  if (hasAny(text, SERVICE_MARKS) || MAINTENANCE_ABBR.test(topic ?? '')) return 'service';

  return 'install';
}
