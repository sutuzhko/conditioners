import type { DayKey } from '@/shared/lib/calendar';

import type { ScheduleItem } from './schedule';

/**
 * Можно ли перенести запись перетаскиванием (ADR-165, отменяет часть ADR-140).
 *
 * 🔴 Правило живёт здесь, а не в обработчике мыши: «что можно двигать» — это
 * доменное решение, и проверять его нужно тестом, а не наведением курсора.
 *
 * Дело — да: у него нет ни монтажника, ни денег, ни уведомления о переносе,
 * обходить перетаскиванием нечего. Наряд и заявка — нет: у наряда за формой
 * стоит уведомление монтажнику и расчёт, у заявки — свой путь, и молчаливый
 * сдвиг мышью обошёл бы и то и другое (ADR-093).
 *
 * Отлучки здесь пока нет намеренно: её перенос обязан сохранять длительность
 * диапазона, а дата окончания появляется в схеме отдельной задачей (#144).
 * Чужая запись не двигается вовсе — у неё нет правки (`edit === null`).
 */
export function isDraggable(item: ScheduleItem): boolean {
  return item.entity === 'event' && item.edit !== null && item.edit.kind === 'event';
}

/**
 * На сколько колонок уехал курсор по горизонтали.
 *
 * Ширину колонки меряет сама сетка и передаёт числом: общая с CSS константа
 * разошлась бы с раскладкой на первой правке шаблона колонок. Неизмеренная
 * колонка (ширина ноль) не двигает запись — это не ошибка, а состояние до
 * первой отрисовки.
 */
export function columnShift(deltaPx: number, columnWidth: number): number {
  if (columnWidth <= 0) return 0;

  return Math.round(deltaPx / columnWidth);
}

/**
 * День, на который запись отпустили.
 *
 * 🔴 Выбор идёт по показанным колонкам, а не арифметикой над датой: за краем
 * сетки колонки нет, и запись, уехавшая туда, пропала бы с экрана в тот же
 * миг. Поэтому сдвиг зажат в границы недели, а незнакомый день (колонка
 * сменилась, пока запись тащили) остаётся собой.
 */
export function dayOfDrop(days: readonly DayKey[], day: DayKey, shift: number): DayKey {
  const index = days.indexOf(day);
  if (index < 0) return day;

  const target = Math.min(Math.max(index + shift, 0), days.length - 1);

  return days[target] ?? day;
}
