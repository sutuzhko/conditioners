/**
 * Тексты чипа погоды (макет, «HERO»).
 *
 * 🔴 Города здесь нет — и в самом чипе его тоже нет (issue #253, закрывает
 * #15): в первом экране Тула названа в плашке охвата и в заголовке, третье
 * повторение ничего не добавляет. Заметка зависит только от температуры и
 * ничего не обещает по срокам — «успейте до очередей» это про спрос, а не
 * про конкретную заявку.
 *
 * 🔴 Строка собрана из двух наборов (issue #254). До 600 чип обязан быть
 * одной строкой, и в ней остаются только подписи, без которых цифры
 * непонятны: «Сегодня +15° · пик за месяц +34°». С 600 к ним возвращаются
 * уточнение среднесуточной и сезонная заметка.
 */

/** Пороги сезонной заметки, °C — из макета. Про поведение спроса, не про технику. */
const PEAK_C = 28;
const SEASON_C = 22;

export const weatherChipContent = {
  today: 'Сегодня',
  /* Уточнение «ср/сут» — не подпись, а пояснение: без него цифра всё равно
     читается как сегодняшняя температура. Поэтому на телефоне оно уходит
     первым. */
  mean: ': ср/сут',
  /* «за месяц» сказано прямо и не сокращается ни на одной ширине: пик берётся
     за последние тридцать дней, и умалчивать об этом нельзя — в прохладный
     день цифра иначе выглядит ошибкой сервиса. */
  peak: 'пик за месяц',
  note: (max: number): string => {
    if (max >= PEAK_C) return 'пик сезона, бронируйте монтаж заранее';
    if (max >= SEASON_C) return 'сезон стартовал, успейте до очередей';
    return 'до жары — свободные даты и спокойные цены';
  },
} as const;
