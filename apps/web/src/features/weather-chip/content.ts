/** Пороги сезонной заметки, °C — из макета. Про поведение спроса, не про технику. */
const PEAK_C = 28;
const SEASON_C = 22;

export const weatherChipContent = {
  today: 'Сегодня:',
  mean: 'ср/сут',
  /* «за месяц» сказано прямо: пик берётся за последние тридцать дней, и
     умалчивать об этом нельзя — в прохладный день цифра иначе выглядит
     ошибкой сервиса. */
  peak: 'пик за месяц',
  note: (max: number): string => {
    if (max >= PEAK_C) return 'пик сезона, бронируйте монтаж заранее';
    if (max >= SEASON_C) return 'сезон стартовал, успейте до очередей';
    return 'до жары — свободные даты и спокойные цены';
  },
} as const;
