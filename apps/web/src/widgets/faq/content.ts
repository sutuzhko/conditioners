import { formatMoney } from '@/shared/lib/format';

import type { FaqEntry, FaqFacts } from './model';

/**
 * Тексты FAQ. Это индексируемый контент и источник разметки `FAQPage`
 * (docs/SEO.md §4), поэтому он отделён от вёрстки и правится чаще неё.
 *
 * 🔴 Ни одного факта о компании (инвариант 8). Цифры, которые в ответах всё же
 * встречаются, — свойства техники из инструкции производителя (заводская
 * заправка на 5–7 м, интервалы обслуживания, ресурс компрессора), а не
 * обещания продавца. Цена монтажа и срок гарантии приходят из базы: см.
 * `buildFaqItems`.
 */
export const faqContent = {
  kicker: '— FAQ —',
  title: 'Частые вопросы',
} as const;

/** Ответ про стоимость: цена берётся из прайса, а не из разметки. */
function priceAnswer(installFrom: number | null): string {
  const opening =
    installFrom === null
      ? 'Типовая квартира — это почти всегда стандартный монтаж по базовой цене из прайса: ' +
        'трасса в пределах включённых метров, кронштейны, вакуумация и запуск уже входят в неё.'
      : `Типовая квартира — это почти всегда стандартный монтаж: от ${formatMoney(installFrom)} ` +
        'с трассой в пределах включённых метров, кронштейнами, вакуумацией и запуском.';

  return (
    `${opening} Дороже выходит только нестандарт: длинная трасса, штробление бетона, ` +
    'высотные работы. Калькулятор монтажа посчитает ваш случай за минуту, и эта же сумма ' +
    'попадёт в договор.'
  );
}

/**
 * Ответ про срок работ. Срок берётся из прайса: сколько идёт монтаж —
 * обещание компании, и в коде его быть не может (инвариант 8).
 */
function durationAnswer(installTerm: string | null | undefined): string {
  const term = installTerm?.trim() ?? '';
  const opening =
    term === ''
      ? 'Типовой монтаж сплит-системы бригада делает за один выезд.'
      : `Типовой монтаж сплит-системы занимает ${term} — один выезд бригады.`;

  return (
    `${opening} Дольше выходит нестандарт: длинная трасса, штробление бетона, ` +
    'высотные работы с промышленным альпинистом. Технику мы привозим с собой, поэтому ' +
    'подбор, доставка и установка укладываются в один день, а не растягиваются на неделю.'
  );
}

/**
 * Ответ про гарантию. Сроки — обязательство компании, они живут в настройках:
 * «три года» в коде разошлись бы с договором при первой же смене условий.
 */
function warrantyAnswer(warranty: FaqFacts['warranty']): string {
  const parts = [warranty?.installation ?? '', warranty?.equipment ?? '']
    .map((part) => part.trim())
    .filter((part) => part !== '');

  if (parts.length === 0) {
    return (
      'Гарантия на монтаж закрывает то, что зависит от нас: герметичность трассы, крепёж и ' +
      'дренаж — приезжаем и устраняем бесплатно. На саму технику действует гарантия ' +
      'производителя, талон оформляем при запуске. Точные сроки указаны в договоре.'
    );
  }

  return parts.join(' ');
}

/**
 * Вопросы главной страницы.
 *
 * 🔴 Отбор по одному правилу: вопрос обязан снимать барьер перед заказом
 * (цена, сроки, согласование, зима, обман с фреоном) или объяснять
 * обслуживание, за которым к нам возвращаются. Справочник по эксплуатации —
 * «какой режим ставить на ночь», «сколько служит кондиционер» — уехал в Базу
 * знаний: там ему место, и там он приводит трафик по информационным
 * запросам, не занимая место в блоке возражений (ADR-074).
 *
 * 🔴 Одна и та же функция кормит и аккордеон, и разметку `FAQPage` — иначе
 * видимый текст и разметка разошлись бы при первой правке ответа, а это
 * основание для ручных санкций (docs/SEO.md §4, инвариант 9).
 */
