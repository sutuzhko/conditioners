import type { Warranty } from '@/entities/settings/model';

/**
 * Вопрос и ответ.
 *
 * 🔴 Ответ — плоская строка, а не разметка: из этого же списка страница
 * собирает `FAQPage` (docs/SEO.md §4), а числа в разметке обязаны совпадать
 * с видимым текстом (инвариант 9). Один источник — расхождение невозможно.
 */
export type FaqEntry = {
  readonly id: string;
  readonly question: string;
  readonly answer: string;
};

/**
 * Факты о компании, которые встречаются в ответах.
 *
 * 🔴 Ни цена монтажа, ни срок гарантии не имеют права лежать в коде
 * (инвариант 8): их правят из админки, и зашитая цифра разошлась бы с
 * таблицей цен на первой же правке. Не переданы — ответ формулируется без
 * них, а не с придуманным умолчанием.
 */
export type FaqFacts = {
  /** Минимальная цена монтажа из прайса, ₽ — та же, что в таблице цен. */
  readonly installFrom?: number | null | undefined;
  /** Условия гарантии из настроек компании. */
  readonly warranty?: Warranty | null | undefined;
};
