/**
 * Контракт блока «Сервис»: диагностика по симптомам.
 *
 * 🔴 Блок в базу не ходит (docs/ORCHESTRATION.md, «Блок не ходит в базу»):
 * разбор симптома приходит либо из `content.ts`, либо целиком пропсом —
 * см. комментарий к `priceFrom`.
 */

/**
 * Разбор одного симптома: что человек видит, вероятная причина и работы.
 *
 * `key` — произвольная строка, а не union: список симптомов допускает приход
 * снаружи, и фиксированный набор ключей в типе сделал бы такие данные
 * непредставимыми.
 */
export type Symptom = {
  /** Ключ для выбора и якоря разбора: `ne-holodit`. */
  readonly key: string;
  /** Подпись чипа — короткая: «Не холодит». */
  readonly label: string;
  /**
   * Ещё короче — для сетки 2×3 на телефоне: «Запах» вместо «Неприятный
   * запах». В колонке 118–165px длинная подпись переносится на вторую
   * строку и ломает ряд. Не задана — на всех ширинах стоит `label`.
   * Обязана быть частью `label` слово в слово: голосовое управление ищет
   * видимую подпись в имени кнопки (WCAG 2.5.3).
   */
  readonly short?: string | undefined;
  /** Заголовок разбора: развёрнутая формулировка запроса из поиска. */
  readonly title: string;
  /** Вероятная причина неисправности. */
  readonly causes: string;
  /** Что делает мастер. */
  readonly fix: string;
  /**
   * Нижняя граница стоимости работ, в рублях.
   *
   * 🔴 Цена — факт о компании (инвариант 8) и обещание, которое повторят по
   * телефону (красная линия «Не врать в цене»). Поэтому в `content.ts` её нет
   * и быть не может: не передали — блок пишет, что посчитаем после
   * диагностики. Передали — показываем «от N ₽».
   */
  readonly priceFrom?: number | undefined;
};
