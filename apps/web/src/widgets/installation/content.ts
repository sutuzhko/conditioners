/** «03» — час суток двумя цифрами: метка ряда и часть подписи ячейки. */
function padHour(hour: number): string {
  return String(hour).padStart(2, '0');
}

/** «6,5» — тариф всегда с одним знаком после запятой, как на ползунке. */
function tariffDecimal(value: number): string {
  return value.toFixed(1).replace('.', ',');
}

