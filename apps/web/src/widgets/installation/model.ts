/**
 * Контракт блока «Монтаж».
 *
 * 🔴 Блок в базу не ходит: шаги и таймлайн — статический контент из
 * `content.ts`, всё остальное приходит пропсами (docs/ORCHESTRATION.md,
 * «Блок не ходит в базу»).
 */

/** Шаг пути клиента: «1 · Заявка и консультация». */
export type InstallStep = {
  /** Номер строкой: рисуется как есть, склейки с индексом массива нет. */
  readonly num: string;
  readonly title: string;
  readonly text: string;
};

/** Пункт таймлайна дня монтажа: «09:00 · Приезд и защита». */
export type InstallDayEntry = {
  /** Время в формате `ЧЧ:ММ` — оно же значение атрибута `datetime` у `<time>`. */
  readonly time: string;
  readonly title: string;
  readonly text: string;
};

/**
 * Границы ползунков расчёта экономии — из макета.
 *
 * Часы — сколько кондиционер реально работает в сутки: два часа это «включаю
 * на ночь», шестнадцать — «работает почти постоянно».
 */
export const HOURS_MIN = 2;
export const HOURS_MAX = 16;
export const HOURS_DEFAULT = 8;

/**
 * Тариф на электричество, ₽/кВт·ч. Диапазон покрывает разброс по стране:
 * от льготного сельского до городского двухтарифного дневного.
 *
 * Стартовое значение — только начальная точка ползунка, не обещание цены:
 * тариф меняется каждый год, поэтому его можно переопределить пропсом.
 */
export const TARIFF_MIN = 4;
export const TARIFF_MAX = 9;
export const TARIFF_STEP = 0.1;
export const TARIFF_DEFAULT = 6.5;
