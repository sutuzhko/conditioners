/**
 * Имя отметки сравнения для скринридера.
 *
 * 🔴 Задаётся `aria-label`, а не собирается из видимой подписи и скрытого
 * хвоста: имя, склеенное из соседних узлов, зависит от того, как их разделит
 * браузер, — а здесь оно должно быть ровно одно и предсказуемое. Видимая
 * подпись входит в него целиком (WCAG 2.5.3), иначе голосовое управление
 * «нажми Сравнить» перестало бы попадать в эту ссылку.
 */
export function compareMarkLabel(name: string, compared: boolean): string {
  return compared
    ? `${catalogText.compareOn}: ${name} — ${catalogText.compareRemove}`
    : `${catalogText.compareAdd}: ${name}`;
}

/** Имя пилюли отмеченной модели: нажатие снимает её из сравнения. */
export function compareChipLabel(name: string): string {
  return `${name} — ${catalogText.compareRemove}`;
}

