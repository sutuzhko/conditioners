/** «до 25 м²» — площадь помещения, на которую рассчитана модель. */
export function areaLabel(areaMax: number): string {
  return `до ${areaMax} м²`;
}

/**
 * Подпись изображения. География обязательна: alt участвует в поиске по
 * картинкам, а запрос всегда с городом (docs/DESIGN_BRIEF.md §8).
 */
export function photoAlt(name: string): string {
  return `${name} — купить в Туле с установкой`;
}

/** Класс мощности словами — для заглушки без фото и для подсказки скринридеру. */
export function powerClassLabel(badge: string): string {
  return `Класс мощности ${badge}`;
}

/** Вычисленный процент скидки: «−12%». Минус — типографский, не дефис. */
export function discountLabel(percent: number): string {
  return `−${percent}%`;
}

/** Срок действия скидки микроподписью: «до 31 октября 2026». */
export function saleUntilLabel(date: string): string {
  return `до ${date}`;
}
