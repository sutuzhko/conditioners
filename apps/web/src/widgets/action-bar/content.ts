import { pluralize } from '@/shared/lib/plural';

/**
 * Служебные подписи панели действий. Это имена элементов интерфейса, а не
 * контент сайта, но правило «текст отдельно от разметки» действует и на них
 * (docs/CLAUDE.md). Ни телефона, ни названия компании здесь нет и быть не
 * может — они приходят из настроек (инвариант 8).
 */
export const actionBarContent = {
  /**
   * Имя области. На странице это вторая навигационная область после основной,
   * и без собственного имени скринридер объявил бы две одинаковые «навигации».
   */
  label: 'Быстрые действия',
  call: 'Позвонить',
  lead: 'Оставить заявку',
  compare: 'Сравнить',
  /** Номер проговаривается голосом: у кнопки со значком трубки иначе нет предмета. */
  callAria: (phone: string): string => `Позвонить ${phone}`,
  /**
   * Цифра в пилюле глазами читается как счётчик, а голосом — как «Сравнить 2».
   * Подпись называет, чего именно две.
   */
  compareAria: (count: number): string =>
    `Сравнить: ${pluralize(count, 'отмеченная модель', 'отмеченные модели', 'отмеченных моделей')}`,
} as const;
