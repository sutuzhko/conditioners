import type { ButtonLinkHref } from '@/shared/ui';

/**
 * Предложение сравнить отмеченные модели. Панель показывает его вместо кнопки
 * заявки: пока в каталоге что-то отмечено, ближайшее полезное действие —
 * посмотреть отметки, а не открыть форму.
 */
export interface CompareOffer {
  /** Сколько моделей отмечено. Ноль сюда не попадает: предложения тогда нет. */
  readonly count: number;
  /** Адрес страницы сравнения — со всеми отметками и текущим подбором. */
  readonly href: ButtonLinkHref;
}
