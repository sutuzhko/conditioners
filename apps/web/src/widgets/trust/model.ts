import type { Warranty } from '@/entities/settings/model';

/**
 * Контракт блока доверия.
 *
 * 🔴 Блок в базу не ходит: всё, что является фактом о компании — цифры
 * достижений и сроки гарантии, — приходит пропсами, запрос делает страница
 * (docs/ORCHESTRATION.md, «Блок не ходит в базу»).
 */

/**
 * Цифра-достижение для полосы счётчиков: «1200+ установок в Туле».
 *
 * 🔴 Значения по умолчанию у неё быть не может: выдуманный счётчик «выполнено
 * работ» запрещён напрямую (инварианты 8 и 10). Не передали — полосы нет.
 */
export type Achievement = {
  /** Число, которое отсчитывает счётчик. */
  readonly value: number;
  /** Хвост после числа: «+», « года». Склонение задаёт владелец данных. */
  readonly suffix?: string | undefined;
  readonly label: string;
};

/** Ключи карточек услуг: по ним страница задаёт, куда ведёт ссылка карточки. */
export type ServiceKey = 'sale' | 'install' | 'service';

export type { Warranty };
