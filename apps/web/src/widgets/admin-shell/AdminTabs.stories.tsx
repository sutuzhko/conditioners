import type { Meta, StoryObj } from '@storybook/nextjs-vite';

import { AdminTabs } from './AdminTabs';

/**
 * Нижняя панель вкладок: навигация панели на телефоне (ADR-309).
 *
 * 🔴 История заведена ради признака ожидающего на кнопке «Ещё» (issue #670).
 * Признак нельзя увидеть иначе: полоса живёт только ниже 600px, а компонента
 * не было ни в одной истории — то есть его не видели ни глаза, ни инварианты,
 * ни измерения. Ровно так же до этого пропал из виду сам лист «Ещё», и его
 * дефект нашёл владелец на живом стенде, а не проверка.
 *
 * 🔴 Истории закреплены за 390: выше 600px полосы нет вовсе (`display: none`),
 * и на 768 с 1440 в кадр попадал бы пустой документ. Тег `vr-390` — тот же
 * способ, которым закреплены за своими ширинами «Меню на телефоне» и фильтры
 * каталога (ADR-219).
 *
 * Грунт панели проставлен обёрткой: плотность и геометрия приходят из
 * `data-ui="panel"`, который на живой странице ставит `NavState` (ADR-187).
 */
const meta = {
  title: 'Админка/Нижние вкладки',
  component: AdminTabs,
  args: { role: 'owner' },
  tags: ['vr-390'],
  /* Открыт «Календарь работ» — вкладка, а не раздел из листа: подсветка
     «Ещё» имеет свою историю в листе, и здесь она только мешала бы смотреть
     на признак. */
  parameters: { nextjs: { navigation: { pathname: '/admin/crm' } } },
  render: (args) => (
    <div data-ui="panel" style={{ minHeight: 160 }}>
      <AdminTabs {...args} />
    </div>
  ),
} satisfies Meta<typeof AdminTabs>;

export default meta;
type Story = StoryObj<typeof meta>;

/** Четыре раздела и «Ещё». Чисел ещё нет — так полоса выглядела всегда. */
export const Базовое: Story = {};

/**
 * 🔴 За «Ещё» кто-то ждёт: два отзыва на модерации. Точка на плече значка —
 * единственное место, откуда владелец с телефона узнаёт о работе, не открывая
 * лист (issue #670).
 *
 * Числа у «Заказов» и «Заявок» тоже переданы, и это часть истории: обе очереди
 * стоят отдельными вкладками рядом, за «Ещё» не спрятаны — и точку не зажигают.
 */
export const ЕстьОжидающие: Story = {
  args: { counts: { orders: 7, leads: 3, reviews: 2 } },
};
