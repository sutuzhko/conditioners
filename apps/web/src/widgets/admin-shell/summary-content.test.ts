import { describe, expect, it } from 'vitest';

import { adminSummaryContent as texts, dayPartOf, dayShort, dayTitle } from './summary-content';

describe('Шапка «Обзора»', () => {
  /* 🔴 Час берётся из московского времени работ (ADR-080): `getHours()` дал бы
     пояс сервера, и в контейнере «доброе утро» приходило бы в четвёртом часу
     ночи. Поэтому функция принимает уже посчитанное время строкой. */
  it('часть суток считается по времени, а не по часам сервера', () => {
    expect(dayPartOf('03:20')).toBe('night');
    expect(dayPartOf('05:00')).toBe('morning');
    expect(dayPartOf('11:59')).toBe('morning');
    expect(dayPartOf('12:00')).toBe('afternoon');
    expect(dayPartOf('17:59')).toBe('afternoon');
    expect(dayPartOf('18:00')).toBe('evening');
  });

  it('битое время не роняет приветствие', () => {
    expect(dayPartOf('')).toBe('night');
  });

  it('здоровается по имени из сессии', () => {
    expect(texts.greeting('morning', 'Сергей')).toBe('Доброе утро, Сергей');
  });

  /* Имени в учётной записи может не быть: «Доброе утро, admin» звучит как
     обращение к серверу, а не к человеку. */
  it('без имени здоровается безымянно, а не логином', () => {
    expect(texts.greeting('evening', null)).toBe('Добрый вечер');
    expect(texts.greeting('evening', '   ')).toBe('Добрый вечер');
  });

  it('строка дня склоняет число выездов', () => {
    expect(texts.dayLine('Среда, 29 августа', 3)).toBe('Среда, 29 августа · 3 выезда сегодня');
    expect(texts.dayLine('Среда, 29 августа', 1)).toBe('Среда, 29 августа · 1 выезд сегодня');
    expect(texts.dayLine('Среда, 29 августа', 11)).toBe('Среда, 29 августа · 11 выездов сегодня');
  });

  /* Ноль выездов — тоже новость: «выездов сегодня нет» отвечает на вопрос, а
     «0 выездов сегодня» читается как сбой счётчика. */
  it('день без выездов говорит это словами', () => {
    expect(texts.dayLine('Суббота, 1 августа', 0)).toBe('Суббота, 1 августа · выездов сегодня нет');
  });

  it('день недели пишется с заглавной: строка начинает предложение', () => {
    /* 2026-08-29 12:00 по Москве — суббота. */
    expect(dayTitle(new Date('2026-08-29T09:00:00.000Z'))).toBe('Суббота, 29 августа');
  });

  it('короткий день строки — день недели и число, как в макете', () => {
    expect(dayShort(new Date('2026-08-29T09:00:00.000Z'))).toBe('сб, 29');
  });

  /* 🔴 Московский пояс, а не пояс сервера: наряд на час ночи 30-го по Москве
     в UTC приходится на 29-е, и день строки обязан называться тридцатым. */
  it('день считается по Москве, а не по UTC', () => {
    expect(dayShort(new Date('2026-08-29T22:00:00.000Z'))).toBe('вс, 30');
  });

  it('длительность выезда читается часами, а не минутами', () => {
    expect(texts.duration(180)).toBe('3 ч');
    expect(texts.duration(90)).toBe('1 ч 30 мин');
  });

  /* «0 ч 30 мин» — не длительность, а способ занять место в узкой колонке. */
  it('получасовое дело подписано минутами, без нулевых часов', () => {
    expect(texts.duration(30)).toBe('30 мин');
  });
});
