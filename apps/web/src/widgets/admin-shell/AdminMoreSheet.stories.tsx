import type { Meta, StoryObj } from '@storybook/nextjs-vite';

import { Drawer } from '@/shared/ui';

import { AdminMoreFooter, AdminMoreSheet } from './AdminMoreSheet';
import { adminShellContent as texts } from './content';

/**
 * Лист «Ещё» на телефоне: разделы сверх четырёх вкладок, настройки, профиль,
 * сайт, тема и выход (issue #659).
 *
 * 🔴 История заведена потому, что её не было. Лист живёт внутри шторки,
 * которую открывает состояние `AdminTabs`, — и без своей истории его не видели
 * ни снимки, ни инварианты, ни измерения. Дефект нашёл владелец на живом
 * стенде («сами настройки тоже странно выглядят»), а не проверка, и это ровно
 * та цена, которую берёт компонент без витрины.
 *
 * 🔴 Лист живёт в шторке, а шторка уходит порталом в конец `body`. До #672
 * сборщик измерений обходил только `#storybook-root`, файл истории приходил
 * пустым, и рядом стояла вторая история — «Содержимое», тот же лист без
 * шторки, ради чисел. Сборщик научился доходить до содержимого портала, и
 * пара свёрнута обратно: истории со шторкой записывают и поверхность, и поле
 * по бокам, и прижатый подвал с выходом — то, чего лист без шторки не давал
 * вовсе.
 */
const meta = {
  title: 'Админка/Лист «Ещё»',
  component: AdminMoreSheet,
  args: { role: 'owner', activeHref: undefined },
  /* Ширину задаёт сам обход: инварианты и измерения ходят по ширинам панели —
     390, 768, 1440, — и своя ширина у истории отняла бы у них телефон. */
  render: (args) => (
    <Drawer open onClose={() => {}} title={texts.moreTitle} footer={<AdminMoreFooter />}>
      <AdminMoreSheet {...args} />
    </Drawer>
  ),
} satisfies Meta<typeof AdminMoreSheet>;

export default meta;
type Story = StoryObj<typeof meta>;

/** Владелец: три группы — разделы, сайт, настройки и профиль. */
export const Владелец: Story = {};

/**
 * Открыт раздел из листа — «Склад». Подсвечен пункт, а не только вкладка
 * «Ещё»: иначе человек, вернувшийся в лист, не видит, где он находится.
 */
export const ОткрытыйРаздел: Story = {
  args: { activeHref: '/admin/stock' },
};

/**
 * 🔴 За разделами листа стоят очереди: два отзыва ждут модерации (issue #670).
 * На телефоне колонки разделов нет, и до этой правки владелец не узнавал о
 * работе нигде — ни во вкладках, где «Отзывов» не осталось, ни в самом листе.
 *
 * Числа «Заказов» и «Заявок» переданы вместе с остальными и в листе не
 * появляются: обе очереди стоят отдельными вкладками, за «Ещё» их не прячут.
 * История это и показывает — счётчик идёт за разделом, а не за набором чисел.
 */
export const СоСчётчиками: Story = {
  args: { counts: { orders: 7, leads: 3, reviews: 2 } },
};

/**
 * 🔴 Открыт тот самый раздел, у которого есть очередь. Состояние редкое, но
 * своей истории стоит: подсвеченная строка залита акцентом, и капсула счётчика
 * набрана им же — без отдельного правила она растворилась бы в заливке. Ровно
 * это правило и проверяется здесь глазами, а не чтением CSS.
 */
export const ОткрытаяОчередь: Story = {
  args: { activeHref: '/admin/reviews', counts: { orders: 7, leads: 3, reviews: 2 } },
};

/**
 * 🔴 Монтажник: разделов сверх вкладок у него нет вовсе, и групп «Разделы» и
 * «Сайт» в листе не появляется. Заголовок над пустотой сообщал бы, что раздел
 * потерялся, — поэтому пустая группа не рисуется.
 *
 * Счётчики переданы и здесь: очереди все владельца, и монтажнику не должно
 * достаться ни одной цифры — показывать их ему было бы нечем и незачем.
 */
export const Монтажник: Story = {
  args: { role: 'installer', activeHref: '/admin/profile', counts: { orders: 7, reviews: 2 } },
};
