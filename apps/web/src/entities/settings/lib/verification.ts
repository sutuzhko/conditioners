/**
 * Подтверждение прав на сайт в Яндекс.Вебмастере и Google Search Console.
 *
 * 🔴 Владелец копирует из панели поисковика **целый тег** — именно так он там
 * и показан, кнопкой «скопировать». Значение отдельной строкой поисковик не
 * предлагает, и требовать его — значит требовать ручной разборки разметки
 * (issue #679). Поэтому обе формы вставки дают один и тот же результат:
 * из `<meta name="yandex-verification" content="abc123" />` берётся `abc123`,
 * а голое `abc123` остаётся собой.
 *
 * Без этого разбора первая же попытка дала бы экранированный тег внутри тега:
 * проверка прав провалилась бы, а причину в панели увидеть негде.
 */

/**
 * Что бывает значением подтверждения: буквы, цифры и знаки, которые
 * встречаются в токенах обоих поисковиков (`-`, `_`, `.`, `=`). Пробелов,
 * угловых скобок и кавычек там не бывает — если они есть, вставлено не то.
 */
const TOKEN = /^[A-Za-z0-9._=-]{1,200}$/;

/** Значение атрибута `content` в кавычках любого вида. */
const CONTENT_ATTRIBUTE = /content\s*=\s*(?:"([^"]*)"|'([^']*)')/i;

/**
 * Значение подтверждения из того, что вставил владелец.
 *
 * Пустая строка — рабочее состояние: поле необязательное, тега тогда нет.
 * `null` — вставлено не то, и об этом нужно сказать в форме, а не молча
 * сохранить мусор в `<head>`.
 */
export function verificationTokenOf(raw: string): string | null {
  const value = raw.trim();
  if (value === '') return '';

  /* Похоже на тег — значит из тега и берём. Строка с угловой скобкой, но без
     `content`, это чужая разметка или обрезанная копия: принять её нельзя. */
  if (value.includes('<')) {
    const found = CONTENT_ATTRIBUTE.exec(value);
    if (found === null) return null;

    const content = (found[1] ?? found[2] ?? '').trim();
    return TOKEN.test(content) ? content : null;
  }

  return TOKEN.test(value) ? value : null;
}
