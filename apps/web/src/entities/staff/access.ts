/**
 * Матрица доступа: перечни ролей, которыми закрыты страницы панели и ручки
 * `/api/admin/*` (ADR-344, [CRM §6](../../../../../docs/CRM.md)).
 *
 * 🔴 Перечней четыре на всю панель, и заведены они здесь, а не у каждого
 * маршрута. Раздел со своим списком ролей — это ещё одно место, где матрица
 * доступа расходится сама с собой; при двух ролях расхождение стоило одного
 * сплошного ревью (ADR-149), при четырёх оно почти неизбежно.
 *
 * 🔴 Перечень закрытый: роль, которую в нём не назвали, не проходит. Именно
 * так, а не «все, кроме монтажника», — вычитание открывало бы каждую новую
 * роль по умолчанию, и следующая роль въехала бы в чужие разделы молча. Ровно
 * это и случилось в фазе 1: `withAdmin` значил «любой вошедший», и появление
 * `admin` с `manager` открыло им заказы, склад и календарь без единой правки
 * маршрута.
 *
 * 🔴 Модуль лежит в `entities`, а не в `shared`: `shared` не имеет права
 * знать про доменные типы (правило слоёв, ADR-096). Значений Zod он не тянет —
 * роль приезжает сюда только типом, и клиентская колонка панели, читающая эти
 * же перечни, не получает в бандл ни схемы, ни проверки ИНН.
 */
import type { AdminRole } from './model';

/**
 * Любой вошедший: свой профиль, свой пароль, свои сессии.
 *
 * Список выписан значениями, а не собран из `ADMIN_ROLES`: `ADMIN_ROLES` —
 * значение из `model.ts`, а вместе с ним в бандл уезжает Zod. Полноту держит
 * тест рядом.
 */
export const EVERYONE: readonly AdminRole[] = ['owner', 'admin', 'manager', 'installer'];

/**
 * Выездная работа: календарь, наряды, отлучки, остатки в машине.
 *
 * Менеджера здесь нет до фазы 3 плана «Роли и права»: наряд везёт
 * вознаграждение исполнителя и удержания, а вырезать их из ответов API —
 * отдельная задача. Пункт меню, ведущий к чужим деньгам, хуже отсутствующего.
 */
export const FIELD: readonly AdminRole[] = ['owner', 'installer'];

/**
 * Жизненный цикл клиента: обращение — звонок — наряд (ADR-344).
 *
 * 🔴 Монтажника здесь нет и не будет: обращения и клиенты — персональные
 * данные, которых он по работе не касается (CRM §6).
 */
export const CLIENT_CYCLE: readonly AdminRole[] = ['owner', 'admin', 'manager'];

/** Только владелец: деньги, витрина, люди, настройки. */
export const OWNER: readonly AdminRole[] = ['owner'];

/** Имя перечня — то, чем матрица доступа записана в таблицах контрактных тестов. */
export type RoleListName = 'EVERYONE' | 'FIELD' | 'CLIENT_CYCLE' | 'OWNER';

/**
 * Перечни по имени.
 *
 * 🔴 Нужен контрактным тестам: они спрашивают у маршрута его перечень и
 * обязаны назвать его словом, которое читается в таблице. Сравнение идёт по
 * тождеству, а не по составу ролей: маршрут, выписавший роли массивом по
 * месту, теста не пройдёт, даже если состав совпал, — а второй источник
 * правды и опасен именно тем, что сегодня он совпадает.
 */
export const ROLE_LISTS: Readonly<Record<RoleListName, readonly AdminRole[]>> = {
  EVERYONE,
  FIELD,
  CLIENT_CYCLE,
  OWNER,
};

/**
 * Имена перечней перечислением.
 *
 * `Object.keys` отдал бы `string[]`, и вызывающему пришлось бы приводить тип;
 * список типизирован именами, а его полноту сверяет тест рядом.
 */
export const ROLE_LIST_NAMES: readonly RoleListName[] = [
  'EVERYONE',
  'FIELD',
  'CLIENT_CYCLE',
  'OWNER',
];
