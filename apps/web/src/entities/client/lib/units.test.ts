import { describe, expect, it } from 'vitest';

import {
  dayOf,
  serviceDueDay,
  shiftDayByMonths,
  unitsToCreate,
  warrantyEndDay,
  warrantyMonths,
  warrantyOver,
} from './units';

describe('срок гарантии из настроек', () => {
  it.each([
    ['год', 12],
    ['1 год', 12],
    ['3 года', 36],
    ['три года', 36],
    ['полтора года', 18],
    ['36 месяцев', 36],
    ['18 мес.', 18],
    ['1,5 года', 18],
    ['Гарантия на монтаж — 3 года. Течь трассы устраняем бесплатно.', 36],
  ])('«%s» → %i месяцев', (term, months) => {
    expect(warrantyMonths(term)).toBe(months);
  });

  it('🔴 «от 1 до 5 лет» датой не становится: это обещание с оговоркой', () => {
    expect(
      warrantyMonths('Гарантия производителя — от 1 до 5 лет в зависимости от модели'),
    ).toBeNull();
  });

  it('🔴 «до трёх лет» — тоже не срок', () => {
    expect(warrantyMonths('до трёх лет')).toBeNull();
  });

  it('🔴 два разных срока в одном поле выбирать за владельца нельзя', () => {
    expect(warrantyMonths('год на монтаж, 3 года на компрессор')).toBeNull();
  });

  it('один и тот же срок, названный дважды, неоднозначным не считается', () => {
    expect(warrantyMonths('3 года на работы и 3 года на технику')).toBe(36);
  });

  it.each([
    ['', 'пустое поле'],
    ['по договору', 'срока нет вовсе'],
    ['место установки согласуем', 'слово «место» — не месяцы'],
    ['годный к эксплуатации', '«годный» — не год'],
    ['200 лет', 'за пределами осмысленного срока'],
  ])('«%s» → пусто (%s)', (term) => {
    expect(warrantyMonths(term)).toBeNull();
  });
});

describe('календарь техники', () => {
  it('гарантия и ТО считаются от дня монтажа', () => {
    expect(warrantyEndDay('2026-07-14', 36)).toBe('2029-07-14');
    expect(serviceDueDay('2026-07-14')).toBe('2027-07-14');
  });

  it('🔴 число прижимается к длине месяца: 31 января + месяц — это февраль', () => {
    expect(shiftDayByMonths('2026-01-31', 1)).toBe('2026-02-28');
    expect(shiftDayByMonths('2024-01-31', 1)).toBe('2024-02-29');
  });

  it('перевод через границу года', () => {
    expect(shiftDayByMonths('2026-12-15', 1)).toBe('2027-01-15');
  });

  it('🔴 отрицательный сдвиг не ломает ключ дня: остаток в JS бывает со знаком', () => {
    expect(shiftDayByMonths('2026-01-15', -1)).toBe('2025-12-15');
    expect(shiftDayByMonths('2026-03-31', -1)).toBe('2026-02-28');
    expect(shiftDayByMonths('2026-05-10', -12)).toBe('2025-05-10');
  });

  it('день монтажа берётся в поясе работ, а не в поясе машины', () => {
    // 22:30 UTC 13 июля — это уже 14 июля в Туле, и монтаж был четырнадцатого
    expect(dayOf('2026-07-13T22:30:00.000Z')).toBe('2026-07-14');
  });

  it('гарантия действует весь последний день', () => {
    expect(warrantyOver('2026-08-27', '2026-08-27')).toBe(false);
    expect(warrantyOver('2026-08-26', '2026-08-27')).toBe(true);
  });
});

describe('перенос техники из наряда без дублей', () => {
  /* Позиция наряда — объект; здесь она сведена к названию, которое и решает. */
  const name = (value: string): string => value;

  it('первое закрытие наряда заводит все позиции', () => {
    expect(unitsToCreate(['Сплит-система 09', 'Сплит-система 12'], [], name)).toEqual([
      'Сплит-система 09',
      'Сплит-система 12',
    ]);
  });

  it('🔴 повторное закрытие ничего не добавляет', () => {
    expect(unitsToCreate(['Сплит-система 09'], ['Сплит-система 09'], name)).toEqual([]);
  });

  it('🔴 два одинаковых блока в одной квартире — две записи, а не одна', () => {
    expect(unitsToCreate(['Сплит 09', 'Сплит 09'], ['Сплит 09'], name)).toEqual(['Сплит 09']);
  });

  it('дописанная после закрытия позиция появляется, остальные — нет', () => {
    expect(unitsToCreate(['Сплит 09', 'Завеса 1500'], ['Сплит 09'], name)).toEqual(['Завеса 1500']);
  });

  it('регистр и лишние пробелы одну и ту же модель не раздваивают', () => {
    expect(unitsToCreate(['Сплит 09'], [' сплит 09 '], name)).toEqual([]);
  });
});
