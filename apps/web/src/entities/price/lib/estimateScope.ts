import type { InstallationInput } from '../model';

/**
 * Границы шкал калькулятора: докуда доходит ползунок трассы и список
 * количества блоков. Это границы интерфейса, а не условия сметы — ставки и
 * пороги живут в настройках (ADR-029), а сюда числа приходят снаружи.
 */
export type EstimateLimits = {
  readonly trassaMaxM: number;
  readonly qtyMax: number;
};

/**
 * Чем закончится расчёт: суммой по формуле или разговором по телефону.
 */
export type EstimateScope = 'formula' | 'site-visit';

/**
 * 🔴 Где формула перестаёт считать честно.
 *
 * Красная линия проекта: всё, что калькулятор показал, обязано совпасть с
 * тем, что скажут по телефону. На верхнем делении шкалы интерфейс не знает
 * настоящего значения — пятнадцать метров трассы на ползунке и двадцать пять
 * метров на объекте выглядят одинаково, а четыре блока в списке означают уже
 * мульти-сплит, где один наружный блок работает на несколько внутренних и
 * умножение цены одиночного монтажа не действует. Показать в этих случаях
 * точную сумму — значит назвать число, которого по телефону не подтвердят.
 *
 * Функция чистая и живёт в домене, а не в вёрстке: компонент рисует то, что
 * ему вернули, и ни одного порога внутри себя не держит.
 */
export function estimateScope(input: InstallationInput, limits: EstimateLimits): EstimateScope {
  const outOfScale = input.trassaM >= limits.trassaMaxM || input.qty >= limits.qtyMax;

  return outOfScale ? 'site-visit' : 'formula';
}
