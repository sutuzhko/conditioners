/**
 * Цвет человека в календаре — ADR-123.
 *
 * 🔴 Цвет закреплён за монтажником и не меняется от сессии к сессии: владелец
 * узнаёт «своих» по цвету, а перекраска при каждом входе делает наложение
 * занятости бесполезным. Поэтому краска вычисляется из номера учётной записи,
 * а не раздаётся по порядку в списке — список меняется, номер нет.
 *
 * 🔴 Цвет не единственный признак: рядом всегда стоят инициалы, а в подписи
 * для скринридера — имя целиком. Иначе слой нечитаем при дальтонизме и в
 * монохромной печати (WCAG 1.4.1).
 *
 * Хранить краску негде и не нужно: схема БД от этого не меняется, а на любом
 * устройстве и у любого пользователя один и тот же человек выходит одного и
 * того же цвета — что и требуется.
 */

/** Различимые пары «текст + фон» палитры. Значения — в CSS-модулях. */
export const PERSON_TONES = ['a', 'b', 'c', 'd', 'e', 'f'] as const;

export type PersonTone = (typeof PERSON_TONES)[number];

/**
 * Стабильная краска по номеру учётной записи.
 *
 * Хеш простой (FNV-подобный по кодам символов): криптографии здесь не нужно,
 * нужна повторяемость и ровное размазывание по шести краскам.
 */
export function personTone(id: string): PersonTone {
  let hash = 0;
  for (let index = 0; index < id.length; index += 1) {
    hash = (hash * 31 + id.charCodeAt(index)) % 1_000_003;
  }

  return PERSON_TONES[hash % PERSON_TONES.length] ?? 'a';
}

/**
 * Инициалы для метки: «Дмитрий Соколов» → «ДС».
 *
 * Одно слово даёт одну букву, логин латиницей — тоже: подпись рядом с цветом
 * должна помещаться в полосу шириной с ноготь, а полное имя стоит в
 * `aria-label` и в легенде.
 */
export function initialsOf(title: string): string {
  const words = title
    .trim()
    .split(/\s+/)
    .filter((word) => word !== '');

  const letters = words
    .slice(0, 2)
    .map((word) => word.charAt(0))
    .join('');

  return letters.toLocaleUpperCase('ru-RU');
}
