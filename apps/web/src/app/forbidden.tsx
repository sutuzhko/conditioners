import type { Metadata } from 'next';

import { getAdminSession } from '@/server/auth';

import { FORBIDDEN_CONTENT as t } from './forbidden-content';
import { ForbiddenView } from './ForbiddenView';

/**
 * Страница отказа — 403 (issue #353, CRM.md §6).
 *
 * 🔴 Next отдаёт её с настоящим кодом 403, и это главное, ради чего она
 * существует. Разворот на чужой рабочий экран, стоявший тут раньше, давал
 * 307: браузер увозил человека прочь, а `curl` получал ответ, по которому
 * нельзя отличить «нельзя» от «переехало». Отказ обязан выглядеть отказом и
 * для человека, и для программы.
 *
 * Кто её видит — монтажник, набравший адрес раздела владельца. Он уже вошёл,
 * поэтому здесь нет ни формы входа, ни списка разделов сайта: выход один — на
 * его собственный рабочий экран.
 *
 * Разметка живёт в клиентском листе: он чинит служебный документ Next, в
 * котором показывается отказ. Заголовок вкладки остаётся здесь — метаданные
 * клиентскому компоненту не принадлежат.
 */
export const metadata: Metadata = {
  title: t.title,
  robots: { index: false, follow: false },
};

/**
 * 🔴 Роль читается здесь, а не приходит от раскладки: границе отказа Next не
 * передаёт от неё ничего. Без роли не выбрать выход — менеджер, отправленный
 * на календарь выездов, получил бы второй отказ вместо выхода из первого
 * (ADR-344). В базу за этим уходит ноль запросов: `getAdminSession` обёрнут
 * `cache()`, и сессию за этот запрос уже прочитала раскладка панели, которая
 * отказ и бросила.
 *
 * Разворачивать на вход при истёкшей сессии нельзя: разворот — это 307, а
 * ответ обязан остаться 403 (issue #353). Поэтому вход предлагается ссылкой.
 */
export default async function Forbidden() {
  const session = await getAdminSession();

  return <ForbiddenView role={session?.role ?? null} />;
}
