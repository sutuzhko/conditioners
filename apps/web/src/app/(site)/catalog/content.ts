import { CATALOG_PATH, SITE_ROUTES } from '@/shared/seo';

/**
 * Тексты маршрутов каталога: заголовок страницы, метаданные листинга и
 * шаблоны для страницы модели (ADR-109).
 *
 * 🔴 Ни одного факта о компании и ни одной характеристики товара (инвариант 8):
 * названия моделей, цены, классы и площади приходят из базы. Город в `h1`
 * зашит осознанно (ADR-107), а в `description` подставляется из настроек —
 * там он приходит аргументом `place` готовым хвостом «в Туле».
 */
export const catalogPageContent = {
  /** Подпись раздела в хлебных крошках — из карты адресов, чтобы след,
      карта сайта и страница 404 называли раздел одинаково. */
  sectionTitle: SITE_ROUTES.find((route) => route.path === CATALOG_PATH)?.title ?? 'Каталог',

  kicker: '— Каталог —',
  title: 'Кондиционеры в Туле — весь каталог',
  lead: 'Всё, что есть в продаже: цена под ключ вместе с базовым монтажом. Выберите класс мощности или площадь помещения — покажем модели, которые её потянут.',

  /** Шаблон заголовка листинга — docs/SEO.md §3, до 60 символов вместе с брендом. */
  metaTitle: 'Каталог кондиционеров — цены с установкой',
  metaDescription: (place: string): string =>
    `Кондиционеры и сплит-системы${place}: цена под ключ вместе с монтажом, ` +
    `подбор по площади помещения и классу мощности. Характеристики, фото и ` +
    `заявка на установку в один день.`,

  /** Заголовок страницы модели, когда владелец не задал свой (docs/SEO.md §3). */
  modelTitle: (name: string, place: string): string => `${name} — купить${place} с установкой`,
  /**
   * Описание страницы модели из её же данных. Цена — действующая: описание в
   * выдаче обязано совпадать с тем, что человек увидит на странице.
   */
  modelDescription: (params: {
    readonly name: string;
    readonly badge: string;
    readonly areaMax: number;
    readonly price: string;
    readonly place: string;
  }): string =>
    `${params.name} — кондиционер класса ${params.badge} на помещение до ` +
    `${params.areaMax} м². Цена ${params.price} под ключ${params.place}: ` +
    `характеристики, фото и заявка на установку.`,
} as const;
