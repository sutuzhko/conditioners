import { notFound } from 'next/navigation';

/**
 * Ловушка несуществующих адресов панели — issue #631.
 *
 * 🔴 Без неё `/admin/nosuchpage` разбирался корневым `app/not-found.tsx`, и
 * вошедший видел витрину сайта: шапку «Каталог · Монтаж · Цены», кнопку
 * заявки и подвал. Он терял разом и место, и панель — вернуться можно было
 * только набрав адрес заново.
 *
 * Вложенный `not-found.tsx` сам по себе этого не чинит: он ловит `notFound()`
 * из своего сегмента, а несовпавший адрес до сегмента не доходит вовсе.
 * Поэтому здесь стоит перехват всего, что не разобрали статические маршруты
 * панели: он бросает `notFound()`, границей служит `not-found.tsx` этой же
 * группы, и 404 рисуется внутри оболочки, с колонкой разделов.
 *
 * Статические маршруты сильнее перехвата, поэтому `/admin/login` и все
 * разделы разбираются по-прежнему.
 */
export default function AdminPanelCatchAllPage(): never {
  notFound();
}
