import { RowsSkeleton } from '@/widgets/admin-shell';

import styles from '../leads/page.module.css';

/**
 * Заготовка списка отзывов (issue #495, #579, ADR-239).
 *
 * 🔴 Одна и та же и на переходе в раздел (`loading.tsx`), и на месте
 * асинхронного блока (`DataBlock`): две разные заготовки одного экрана
 * разошлись бы по высоте, и раскладка перестраивалась бы дважды — сначала под
 * заготовку перехода, потом под заготовку блока.
 *
 * Четыре строки и высота `reviewSkeleton` сняты с готовой страницы: карточка
 * отзыва на телефоне вдвое выше, чем на широком экране, и одним числом её не
 * описать — высоту задаёт класс, а не проп.
 *
 * `aria-busy` приносит `RowsSkeleton`: он и есть контейнер, который ждёт
 * данные, а сами полосы от озвучки скрыты.
 */
export function ReviewsSkeleton() {
  return <RowsSkeleton rows={4} className={styles.reviewSkeleton} />;
}
