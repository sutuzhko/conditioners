import type { ReactNode } from 'react';

/**
 * Раздел базы знаний: содержимое и слот окна.
 *
 * 🔴 Создание собирается перехватывающим маршрутом (ADR-117). Переход из
 * списка рисует `@modal` поверх него — список под окном не двигается, «назад»
 * закрывает, ссылку на форму можно прислать. Прямой заход по тому же адресу
 * перехвата не проходит и отдаёт обычную страницу: иначе присланная ссылка
 * вела бы в пустоту, а F5 терял бы набранный текст.
 *
 * Стража роли здесь нет намеренно: проверка выше страницы успевает сменить
 * адрес, но не остановить чтение данных (ADR-095). Её место — первая строка
 * каждой страницы раздела, включая страницы за перехватом.
 */
export default function KnowledgeLayout({
  children,
  modal,
}: {
  readonly children: ReactNode;
  readonly modal: ReactNode;
}) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
