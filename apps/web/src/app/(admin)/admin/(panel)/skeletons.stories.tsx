import type { Meta, StoryObj } from '@storybook/nextjs-vite';

import { AdminSummarySkeleton } from '@/widgets/admin-shell';

import { CatalogTableSkeleton } from './catalog/CatalogSkeleton';
import { LeadsSkeleton } from './leads/LeadsSkeleton';
import { OrdersSkeleton } from './orders/OrdersSkeleton';
import { StockSkeleton } from './stock/StockSkeleton';

/**
 * Скелетоны разделов панели — то, что человек видит до прихода данных
 * (issue #334, #651).
 *
 * 🔴 Зачем истории на скелетоны. Скелетон обязан занимать ту же высоту, что и
 * готовый блок, иначе список прыгает под уже прочитанным заголовком.
 * Проверить это сквозным сценарием нельзя: попадёт заготовка в ответ или нет,
 * решает гонка сервера с самим собой — успели ли данные к первому сбросу
 * потока. Разовый замер эту гонку обходит, но регресс не сторожит.
 *
 * История сторожит: файл измерений на каждый скелетон лежит в git, и правка
 * высоты заготовки видна диффом PR, как у любой другой истории (ADR-234).
 *
 * 🔴 Заготовки больше не файлы `loading.tsx`, а компоненты рядом со своей
 * страницей (issue #651). Заготовка на границе раздела уходила в ответ первой
 * и уносила с собой код ответа: `notFound()` удалённой записи заставал статус
 * уже отправленным, и адрес отвечал 200. Теперь каждая стоит внутри своего
 * `Suspense`, а страница успевает сказать «не найдено» до первого байта.
 *
 * Истории живут в каталоге маршрута рядом со скелетонами, а не в `widgets`:
 * слою `widgets` запрещено импортировать из `app`, а заготовка раздела — это
 * файл маршрута. Next собирает в каталоге только свои имена (`page`,
 * `layout`), соседний `.stories.tsx` ему не мешает.
 *
 * Разделы взяты не все, а по одному на устройство скелетона: две колонки
 * (заявки), стопки с фильтрами и таблицей (заказы), плитки с таблицей
 * (склад), полотно списка (каталог) и сводка на входе.
 */
const meta = {
  title: 'Админка/Скелетоны разделов',
  parameters: { layout: 'fullscreen' },
} satisfies Meta;

export default meta;
type Story = StoryObj<typeof meta>;

/** Заявки: очередь и карточка обращения. */
export const Заявки: Story = { render: () => <LeadsSkeleton /> };

/** Заказы: лента стопок, ряд фильтров и таблица нарядов. */
export const Заказы: Story = { render: () => <OrdersSkeleton /> };

/** Склад: плитки остатка, фильтры и таблица «позиции × зоны». */
export const Склад: Story = { render: () => <StockSkeleton /> };

/** Каталог: полотно таблицы моделей. */
export const Каталог: Story = { render: () => <CatalogTableSkeleton /> };

/** Сводка на входе: плитки, ближайшие дела и готовность последней (ADR-241). */
export const Обзор: Story = { render: () => <AdminSummarySkeleton /> };
