import type { ReactNode } from 'react';

/**
 * Раздел каталога: содержимое и слот окна.
 *
 * 🔴 Окно создания собирается перехватывающим маршрутом (ADR-117). Переход из
 * списка рисует `@modal` поверх него — таблица под окном не двигается, «назад»
 * закрывает, ссылку на форму можно прислать. Прямой заход по тому же адресу
 * перехвата не проходит и отдаёт обычную страницу: иначе ссылка на форму
 * создания вела бы в пустоту, а F5 терял ввод.
 *
 * Стража роли здесь нет намеренно: проверка выше страницы успевает сменить
 * адрес, но не остановить чтение данных (ADR-095). Её место — загрузчик
 * данных каждой страницы раздела, включая страницы за перехватом.
 */
export default function CatalogLayout({
  children,
  modal,
}: {
  readonly children: ReactNode;
  readonly modal: ReactNode;
}) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
