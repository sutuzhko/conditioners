import type { ReactNode } from 'react';

/**
 * Раздел клиентов: содержимое и слот окна.
 *
 * 🔴 Окно создания собирается перехватывающим маршрутом (ADR-117). Переход из
 * списка рисует `@modal` поверх него — карточки под окном не двигаются, «назад»
 * закрывает окно, ссылку на форму можно прислать. Прямой заход по тому же
 * адресу перехвата не проходит и отдаёт обычную страницу: иначе ссылка на
 * форму создания вела бы в пустоту, а F5 терял ввод.
 *
 * Стража роли здесь нет намеренно: проверка выше страницы успевает сменить
 * адрес, но не остановить чтение данных (ADR-095). Её место — первая строка
 * каждой страницы раздела, включая страницы за перехватом.
 */
export default function ClientsLayout({
  children,
  modal,
}: {
  readonly children: ReactNode;
  readonly modal: ReactNode;
}) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
