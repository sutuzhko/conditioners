import type { ReactNode } from 'react';

/**
 * Раздел склада: содержимое и слот окна.
 *
 * 🔴 Окно создания собирается перехватывающим маршрутом (ADR-117, ADR-137).
 * Переход из раздела рисует `@modal` поверх списка — таблица под ним не
 * двигается, «назад» закрывает окно, ссылку на форму можно прислать. Прямой
 * заход по тому же адресу перехвата не проходит и отдаёт обычную страницу:
 * иначе ссылка на форму создания вела бы в пустоту, а F5 терял ввод.
 *
 * Стража роли здесь нет намеренно: проверка выше страницы успевает сменить
 * адрес, но не остановить чтение данных (ADR-095). Её место — первая строка
 * каждой страницы раздела, включая страницы за перехватом.
 */
export default function StockLayout({
  children,
  modal,
}: {
  readonly children: ReactNode;
  readonly modal: ReactNode;
}) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
