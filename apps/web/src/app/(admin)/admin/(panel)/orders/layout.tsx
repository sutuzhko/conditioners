import type { ReactNode } from 'react';

/**
 * Раздел нарядов: содержимое и слот окна.
 *
 * 🔴 Окно создания собирается перехватывающим маршрутом (ADR-117). Переход из
 * списка рисует `@modal` поверх него — список под окном не двигается, «назад»
 * закрывает окно, ссылку на форму можно прислать. Прямой заход по тому же
 * адресу перехвата не проходит и отдаёт обычную страницу: иначе ссылка на
 * форму заведения вела бы в пустоту, а F5 терял ввод.
 *
 * Стража роли здесь нет намеренно: проверка выше страницы успевает сменить
 * адрес, но не остановить чтение данных (ADR-095). Её место — сама страница,
 * а для формы заведения — загрузчик `data.ts`, который она вызывает первым.
 */
export default function OrdersLayout({
  children,
  modal,
}: {
  readonly children: ReactNode;
  readonly modal: ReactNode;
}) {
  return (
    <>
      {children}
      {modal}
    </>
  );
}
