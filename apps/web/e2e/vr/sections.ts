export const COVERED_SECTIONS: readonly string[] = [
  ...PUBLIC_SECTIONS,
  ...PANEL_SECTIONS,
  FIXTURES_SECTION,
];

/** Раздел истории — первый сегмент её названия вместе со слешем. */
export function sectionOf(title: string): string {
  const [head] = title.split('/');
  return head === undefined ? title : `${head}/`;
}
