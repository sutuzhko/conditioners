/**
 * Разделы витрины и работы, которые их проверяют.
 *
 * 🔴 Список один на все работы (issue #517). До этого он был зашит в четырёх
 * файлах порознь, и два раздела не попали ни в один: `Фичи/` — формы заявки,
 * отзыва и напоминания, то есть самая дорогая точка сайта, — и
 * `Календарь/` — подсказка по клавишам и поиск. Их истории не снимались, не
 * мерились и не проверялись инвариантами, **и ни одна работа об этом не
 * сообщала**: прогон был зелёным, потому что проверять было нечего.
 *
 * Проверять надо не «зелено ли», а «попало ли в список» — за этим следит
 * `invariants/stories.spec.ts`: раздел, которого нет ни в одном перечне
 * ниже, красит прогон.
 */

/**
 * Публичная часть целиком — для инвариантов и измерений. Ширины — `VR_WIDTHS`.
 */
export const PUBLIC_SECTIONS = ['Блоки/', 'Страницы/', 'Фичи/'] as const;

/**
 * Публичная часть под **пиксельные снимки**: без `Фичи/`.
 *
 * 🔴 История, чей сценарий выполняет действия — набирает, нажимает, ждёт
 * ответа, — устойчивого кадра не даёт. У форм заявки, отзыва и напоминания
 * это выяснилось трижды подряд и каждый раз по-новому: сначала номер,
 * набранный посимвольно, выходил разным (#526); потом кольцо фокуса
 * появлялось через раз; потом остались одиночные кадры на случайных ширинах.
 * Снимку нужен устоявшийся экран, а сценарий истории его не гарантирует.
 *
 * Из проверок раздел при этом **не выпадает**: инварианты и измерения читают
 * уже устоявшийся DOM и потому стабильны — и именно они находили настоящие
 * дефекты, тогда как снимки этих историй давали шум, красивший чужие PR.
 */
export const PUBLIC_SNAPSHOT_SECTIONS = ['Блоки/', 'Страницы/'] as const;

/**
 * Кит панели под снимки: `UI Kit/` — основной раздел, `Кит/` — два
 * компонента, заведённые под этим именем раньше (Icon и PhoneInput).
 */
export const PANEL_KIT_SECTIONS = ['UI Kit/', 'Кит/'] as const;

/**
 * Панель целиком для инвариантов и измерений: к киту добавляются экраны.
 * Пикселями `Админка/` пока не снимается — историям нужны фикстуры (#427).
 */
export const PANEL_SECTIONS = [...PANEL_KIT_SECTIONS, 'Админка/'] as const;

/** Истории-фикстуры инвариантов: нарочно сломаны, у них свой спек. */
export const FIXTURES_SECTION = 'Фикстуры/';

/**
 * Все разделы, у которых есть работа. Раздел, которого здесь нет, считается
 * непокрытым — и это отказ, а не молчание.
 */
export const COVERED_SECTIONS: readonly string[] = [
  ...PUBLIC_SECTIONS,
  ...PANEL_SECTIONS,
  FIXTURES_SECTION,
];

/** Раздел истории — первый сегмент её названия вместе со слешем. */
export function sectionOf(title: string): string {
  const [head] = title.split('/');
  return head === undefined ? title : `${head}/`;
}
