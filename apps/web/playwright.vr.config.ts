import { defineConfig } from '@playwright/test';

/**
 * Визуальная регрессия: снепшоты историй Storybook на четырёх ширинах
 * в обеих темах (ADR-021). Свой раннер, без Chromatic.
 *
 * Браузер — системный chromium из образа: собственные сборки Playwright для
 * musl не выпускаются (docs/BUGS.md). Путь приходит переменной, чтобы раннер
 * запускался и вне контейнера, где браузеры ставит сам Playwright.
 */
export const VR_WIDTHS = [320, 375, 768, 1200] as const;
export const VR_THEMES = ['light', 'dark'] as const;

/**
 * 🔴 У панели свои ширины (issue #404, ADR-207). Публичные
 * 320 / 375 / 768 / 1200 не проверяют у неё ничего важного: оболочка панели
 * переключается по порогам 900 и 1200 и живёт на 390 / 768 / 1440, а высоты
 * контролов растут по кадру ниже 900 (ADR-183). Снимая панель на 375 и 1200,
 * мы не увидели бы ни телефонной раскладки, ни десктопной, ни границы 900.
 *
 * Ширин три, а не четыре: 390 — телефон, 768 — планшет и та сторона порога
 * 900, где панель ещё сенсорная, 1440 — десктоп с развёрнутой колонкой
 * разделов. Четвёртая ширина стоила бы трети времени работы и не проверяла бы
 * ни одного собственного порога панели.
 */
export const VR_PANEL_WIDTHS = [390, 768, 1440] as const;

// `--no-sandbox`: в контейнере процесс идёт от root, и песочница Chromium
// обрывает загрузку страниц. Изоляция здесь и так контейнерная.
const chromiumPath = process.env.CHROMIUM_PATH;
const launchOptions =
  chromiumPath === undefined
    ? {}
    : {
        executablePath: chromiumPath,
        args: ['--no-sandbox', '--disable-dev-shm-usage'],
      };

export default defineConfig({
  testDir: './e2e/vr',
  fullyParallel: true,
  retries: 0,

  /**
   * 🔴 Каталог кадров приходит снаружи (ADR-230). Эталон больше не лежит в
   * репозитории: работа пайплайна снимает кадры `merge-base` и монтирует их в
   * `VR_FRAMES_DIR`, а раннер сравнивает с тем, что там лежит. Без переменной
   * каталог прежний — рядом со спеками, — и он в `.gitignore`: локальный
   * прогон сравнивает с тем, что снял сам.
   */
  snapshotDir: process.env.VR_FRAMES_DIR ?? './e2e/vr',

  /* 🔴 Имя проекта из пути к кадру убрано намеренно (issue #404). По умолчанию
     Playwright вставляет его перед платформой, и имена кадров базы и ветки
     обязаны совпадать буквально — по ним работа находит эталон и называет
     расхождение в сводке. Проекты разводятся по каталогам сами: у каждого
     спека свой `*-snapshots`. */
  /* 🔴 `{snapshotDir}` в начале обязателен. `{testFileDir}` — путь **относительно**
     `testDir`, и для спеков, лежащих прямо в нём, он пуст: шаблон без первой
     части давал абсолютный `/panel.spec.ts-snapshots/…` в корне контейнера, и
     кадры ложились мимо каталога, который забирала работа. */
  snapshotPathTemplate:
    '{snapshotDir}/{testFileDir}/{testFileName}-snapshots/{arg}{-platform}{ext}',

  /* Публичная часть и панель — разные работы пайплайна: у них разные ширины и
     разное время (issue #404). Проекты дают запускать их по отдельности, не
     заводя второго конфига с копией всех настроек. */
  /* 🔴 Шаблоны заякорены на каталог: Playwright сверяет их с абсолютным путём,
     и незаякоренный `/stories\.spec\.ts/` подхватил бы `invariants/stories.spec.ts`
     в проект снимков — обход историй без единого кадра шёл бы под именем `public`. */
  projects: [
    { name: 'public', testMatch: /\/vr\/stories\.spec\.ts$/ },
    { name: 'panel', testMatch: /\/vr\/panel\.spec\.ts$/ },
    /* Инварианты без эталона (ADR-230, фаза 3) — три проекта с разной средой:
       `invariants` обходит все истории витрины и красит на нарушении;
       `invariants-fixtures` — истории-фикстуры с нарочными нарушениями, каждое
       правило обязано поймать своё (issue #456); `invariants-measure` — тесты
       самого измерителя на синтетическом DOM через `page.setContent`, витрина
       ему не нужна (issue #454). Порознь, потому что первые два ждут Storybook,
       а третий идёт где угодно — и им незачем ждать друг друга. */
    { name: 'invariants', testMatch: /\/invariants\/stories\.spec\.ts$/ },
    { name: 'invariants-fixtures', testMatch: /\/invariants\/fixtures\.spec\.ts$/ },
    { name: 'invariants-measure', testMatch: /\/invariants\/measure\.spec\.ts$/ },
  ],
  /* Один тест обходит все истории раздела, поэтому меряется он не секундами.
     Разбивать по тесту на историю нельзя: список приходит из Storybook по
     сети, а Playwright собирает тесты синхронно. */
  timeout: 45 * 60_000,

  /**
   * 🔴 Число потоков выбрано замером, а не по умолчанию (issue #442, ADR-222).
   *
   * Стоял один поток, и восемь тестов публичной работы шли друг за другом:
   * 1504 кадра за 17м56с при четырёх ядрах раннера, три из которых простаивали.
   * Тестов здесь мало и они длинные — по одному на пару «ширина + тема», — так
   * что потоки делят работу почти поровну: восемь тестов в четыре потока это
   * два круга вместо восьми.
   *
   * Определённость от этого не страдает: она держится на явных ожиданиях
   * готовности истории (ADR-217), а не на том, что машина не занята. Занятая
   * машина делает кадр медленнее, но тот же самый.
   *
   * На своей машине поток остаётся один: там дев-сервер, витрина и браузер уже
   * делят четыре ядра, и четвёртый потребитель отнимает больше, чем приносит
   * (ADR-173).
   *
   * 🔴 Число приходит переменной, а не выводится из `CI`. Первая редакция
   * смотрела на `process.env.CI` — и не сработала: снимки идут **внутри
   * контейнера**, а `docker run` переменных раннера не наследует. Внутри `CI`
   * был пуст, поток остался один, и работа как шла семнадцать минут, так и
   * пошла. Явная переменная видна в задании числом, а не подразумевается.
   */
  workers: Number(process.env.VR_WORKERS ?? 1),
  expect: {
    // снимку нужно время устояться: первая история грузится дольше прочих
    timeout: 20_000,
    /**
     * 🔴 Порог задан числом точек, а не долей, и число выбрано по замеру, а не
     * на глаз (29 августа).
     *
     * Было `maxDiffPixelRatio: 0.01` — доля от кадра. На 1200×900 это 10 800
     * точек, и сдвиг вёрстки в **один пиксель** под неё прятался: смещение
     * подвала на 1px меняет от 2 671 до 7 342 точек, то есть проверка его
     * пропускала. Прогон был зелёным при заведомо изменённой вёрстке — ровно то,
     * ради чего снимки и заводились.
     *
     * Шум при этом нулевой: на неизменённом коде 163 истории из 171 совпали с
     * эталоном точка в точку, а разошлись ровно восемь — те, которые и правились.
     * Значит запас нужен не на антиалиасинг между прогонами, а на возможную
     * разницу отрисовки между машинами; 200 точек — это в тринадцать раз меньше
     * самого слабого сигнала и достаточно, чтобы случайная кромка не роняла
     * прогон.
     */
    toHaveScreenshot: { maxDiffPixels: 200 },
  },
  use: {
    baseURL: process.env.VR_BASE_URL ?? 'http://storybook:6006',
    launchOptions,
    /* 🔴 Ожидания обязаны иметь предел. По умолчанию у Playwright его нет, и
       одна история, которая не дойдёт до готовности, останавливает прогон
       навсегда: раннер молчит, а не падает (docs/BUGS.md). */
    actionTimeout: 15_000,
    navigationTimeout: 30_000,
  },
});
