-- Полное наименование организации осталось одно: `legal.name` (ADR-106).
--
-- Поле `company.legalName` уезжало в разметку Organization, но нигде на сайте
-- не показывалось, и с видимыми реквизитами успело разойтись — это инвариант 9.
-- Схема группы `company` строгая (`z.object().strict()`), поэтому забытый ключ
-- в сохранённом JSON уронил бы разбор настроек целиком: убираем его из данных.
--
-- Значение не переносится: `legal.name` заполняется отдельно и обязателен по
-- проверке готовности. Перезаписать им заполненные реквизиты было бы хуже
-- потери — это подмена факта о компании.
UPDATE "Setting"
SET "value" = "value" - 'legalName'
WHERE "key" = 'company' AND "value" ? 'legalName';
