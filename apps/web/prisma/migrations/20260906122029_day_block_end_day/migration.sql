-- Диапазон у отлучки: отпуск на две недели — одна запись, а не четырнадцать
-- (ADR-165). Поле необязательное: у повторяемой занятости диапазона дат нет
-- вовсе, а пустой конец у разовой читается как «в тот же день».
ALTER TABLE "DayBlock" ADD COLUMN     "endDay" TIMESTAMP(3);

-- Приведение заведённых строк: у существующих отлучек окончание равно началу.
-- Разрешение занятости и без этого прочло бы пустой конец как однодневную
-- отлучку, но записанное число не зависит от прочтения: запрос за промежуток
-- дат сравнивает `endDay` напрямую, и строка с пустым концом выпадала бы из
-- выборки при любой правке этого сравнения.
UPDATE "DayBlock" SET "endDay" = "day" WHERE "repeat" = 'ONCE' AND "day" IS NOT NULL;

-- CreateIndex
CREATE INDEX "DayBlock_userId_endDay_idx" ON "DayBlock"("userId", "endDay");
