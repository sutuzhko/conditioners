-- Разрешения администратора: тринадцать разделов и пять опасных действий
-- (ADR-344, issue #781).
--
-- Переключатели владельца над одной ролью — `ADMIN`. Владелец их не
-- спрашивает (он их и раздаёт), у менеджера и монтажника доступ задан ролью
-- целиком, поэтому набор у них остаётся пустым и ни на что не влияет.

-- 1. Словарь. Перечислением, а не строками: раздел, которого в панели нет,
--    база принимать не должна. Порядок значений повторяет
--    `entities/staff/permissions.ts` — сначала тринадцать разделов, потом пять
--    опасных действий.
CREATE TYPE "AdminPermission" AS ENUM ('OVERVIEW', 'CRM', 'ORDERS', 'LEADS', 'CLIENTS', 'TEAM', 'STOCK', 'CATALOG', 'KNOWLEDGE', 'REVIEWS', 'COMPANY', 'PRICES', 'NOTIFICATIONS', 'DATA_DELETE', 'MONEY', 'COMPANY_SETTINGS', 'PEOPLE', 'ACTIVITY_PURGE');

-- 2. Набор у учётной записи. Умолчание — пустой набор: заведённый
--    администратор не получает ни одного раздела, пока владелец их не включил.
--    Доступ, выдаваемый по умолчанию, — это доступ, о котором никто не решал.
ALTER TABLE "AdminUser" ADD COLUMN     "permissions" "AdminPermission"[] DEFAULT ARRAY[]::"AdminPermission"[];

-- 3. 🔴 Действующие записи не остаются с пустым набором — иначе накат сам по
--    себе меняет то, что человеку открыто, и обнаруживается это входом в
--    панель.
--
--    Владелец получает набор целиком. Страж его всё равно не спрашивает —
--    роль `OWNER` проходит мимо разрешений, — но строка обязана быть честной:
--    набор читается и экраном прав, и человеком в дампе, и пустое поле у
--    владельца означало бы «ему ничего не открыто», что неправда. Заодно это
--    защита от обратного порядка проверки: если разрешения когда-нибудь
--    начнут спрашивать и у владельца, панель не закроется.
UPDATE "AdminUser"
SET "permissions" = ARRAY['OVERVIEW', 'CRM', 'ORDERS', 'LEADS', 'CLIENTS', 'TEAM', 'STOCK', 'CATALOG', 'KNOWLEDGE', 'REVIEWS', 'COMPANY', 'PRICES', 'NOTIFICATIONS', 'DATA_DELETE', 'MONEY', 'COMPANY_SETTINGS', 'PEOPLE', 'ACTIVITY_PURGE']::"AdminPermission"[]
WHERE "role" = 'OWNER';

--    Администратор получает ровно то, что было открыто ему до этой миграции:
--    раздел «Заявки» (issue #770, перечень `CLIENT_CYCLE`). Свой профиль
--    переключателем не закрывается и разрешением не является. Набор «всё» ему
--    выдавать нельзя — это ровно тот молчаливый доступ, от которого ADR-344 и
--    отказывается; набор «ничего» отнял бы у него уже работающий раздел.
UPDATE "AdminUser"
SET "permissions" = ARRAY['LEADS']::"AdminPermission"[]
WHERE "role" = 'ADMIN';

-- 4. 🔴 Владелец в системе один (ADR-344, issue #784). Правило держит
--    приложение, но данные обязаны ему соответствовать уже на входе: вторая
--    запись `OWNER`, заведённая до этой миграции, означала бы двух человек с
--    полным доступом к деньгам, и экран прав про неё ничего бы не сказал.
--
--    Накат останавливается с названным числом, а не чинит молча: кого из
--    владельцев понижать — решение владельца, а не миграции. Сообщение идёт
--    исключением: `RAISE NOTICE` движок Prisma не показывает (см. миграцию
--    20260908120000_work_type_dictionary).
DO $$
DECLARE owners integer;
BEGIN
    SELECT count(*) INTO owners FROM "AdminUser" WHERE "role" = 'OWNER';

    IF owners > 1 THEN
        RAISE EXCEPTION
            'ADR-344: владельцев в базе %, а он должен быть один. Накат остановлен: разрешения раздаёт единственная учётная запись, и выбрать её за владельца нельзя. Понизьте лишние записи до ADMIN и повторите выкладку.',
            owners;
    END IF;
END $$;
