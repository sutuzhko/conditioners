-- Заявка получает вид работ (ADR-343, issue #838).
--
-- 🔴 Колонка необязательна, и это не осторожность, а решение: накопленные темы
-- обращений задним числом не разбираются. У всех заявок, пришедших до
-- справочника, вида работ нет — и это честнее, чем угаданный по словам
-- (ADR-343). Заполняться поле начнёт с формы заявки на сайте (фаза 4).
--
-- Свободная тема остаётся своим полем: вид работ отвечает на вопрос «что за
-- работа», тема — «что именно у человека случилось», и второе первым не
-- заменяется.
ALTER TABLE "Lead" ADD COLUMN "workTypeId" TEXT;

CREATE INDEX "Lead_workTypeId_idx" ON "Lead"("workTypeId");

-- `RESTRICT`, как у дела и наряда: занятый вид работ отключают, а не удаляют.
ALTER TABLE "Lead"
    ADD CONSTRAINT "Lead_workTypeId_fkey"
    FOREIGN KEY ("workTypeId") REFERENCES "WorkType"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
