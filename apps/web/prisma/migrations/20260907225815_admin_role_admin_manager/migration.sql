-- Четыре роли вместо двух: администратор и менеджер (ADR-344, issue #767).
--
-- 🔴 Миграция строго дополняющая: она добавляет значения перечисления и не
-- трогает ни одной записи. Владелец остаётся владельцем, монтажники —
-- монтажниками; ролей у них не меняет ни эта миграция, ни какая-либо другая.
-- База дев-окружения одна на все рабочие деревья, и правка существующих строк
-- отсюда означала бы правку чужой работы.
--
-- 🔴 `AFTER`, а не добавление в конец типа. Порядок значений перечисления в
-- Postgres задаётся порядком объявления, и списки команды сортируются по нему
-- (`orderBy: { role: 'asc' }` в `server/repo/admin-users.ts`). Без `AFTER`
-- новые роли встали бы за монтажниками, и лестница доступа в списке читалась
-- бы как «владелец, монтажники, администратор, менеджер».
--
-- Значения добавляются по одному: `ALTER TYPE … ADD VALUE` принимает ровно
-- одно значение за вызов. На Postgres 12 и старше оба вызова допустимы внутри
-- одной транзакции, пока добавленное значение в ней же не используется, — а
-- здесь оно и не используется. Проект работает на Postgres 16.
ALTER TYPE "AdminRole" ADD VALUE 'ADMIN' AFTER 'OWNER';
ALTER TYPE "AdminRole" ADD VALUE 'MANAGER' AFTER 'ADMIN';
