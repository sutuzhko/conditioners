-- Наряд переезжает на справочник видов работ (ADR-343, issue #834).
--
-- Тип наряда и вид дела в календаре были двумя не связанными понятиями:
-- перечисление `OrderType` в схеме и запись справочника. После этой миграции
-- понятие одно, и «монтаж» в наряде красится той же строкой, что «монтаж» в
-- деле, — расхождение перестаёт быть возможным.
--
-- 🔴 Данные обязаны пережить перенос. Соответствие берётся по коду записи
-- справочника, а не по порядку и не по названию: INSTALL → `install`,
-- SERVICE → `service`, REPAIR → `repair`. Те же три кода завела миграция
-- `20260908120000_work_type_dictionary` из прежних значений `ORDER_LOOK`, то
-- есть краски и подписи у наряда остаются ровно теми, к которым владелец
-- привык.

-- 1. Инструмент выезда переезжает в справочник.
--
--    🔴 До сих пор он лежал в коде таблицей на три типа наряда
--    (`entities/order/lib/checklist.ts`) и был последним перечнем видов работ
--    в коде (инвариант 8). Заведи владелец «Чистку дренажа» — монтажник уехал
--    бы на неё без единой строки про инструмент, и дописать её было бы некуда,
--    кроме как правкой кода.
--
--    Списки переносятся дословно: миграция меняет место хранения, а не то, что
--    монтажник кладёт в машину.
ALTER TABLE "WorkType" ADD COLUMN "tools" TEXT[] DEFAULT ARRAY[]::TEXT[];

UPDATE "WorkType" SET "tools" = ARRAY[
    'Перфоратор с бурами и удлинителем',
    'Вакуумный насос и манометрический коллектор',
    'Труборез, вальцовка и трубогиб',
    'Стремянка'
] WHERE "code" = 'install';

UPDATE "WorkType" SET "tools" = ARRAY[
    'Мойка высокого давления и пакет для чистки',
    'Антибактериальное средство, щётки и ветошь',
    'Стремянка'
] WHERE "code" = 'service';

UPDATE "WorkType" SET "tools" = ARRAY[
    'Манометрический коллектор и вакуумный насос',
    'Течеискатель и мультиметр',
    'Баллон с хладагентом'
] WHERE "code" = 'repair';

-- 2. Признак «работа этого вида ставит клиенту технику».
--
--    🔴 Та же причина, что у инструмента: правило жило строкой
--    `order.type !== 'INSTALL'` в `repo/client-units.ts` — то есть новый вид
--    работ владельца молча не заводил бы технику в карточке клиента и не
--    начинал бы отсчёт гарантии. Признак ставится только монтажу: ТО и ремонт
--    приезжают к тому, что уже стоит, — ровно как решала снятая строка.
ALTER TABLE "WorkType" ADD COLUMN "installsUnits" BOOLEAN NOT NULL DEFAULT false;

UPDATE "WorkType" SET "installsUnits" = true WHERE "code" = 'install';

-- 3. Колонка добавляется пустой, заполняется по коду вида и только потом
--    становится обязательной: сделать её `NOT NULL` сразу нельзя — таблица не
--    пуста.
ALTER TABLE "Order" ADD COLUMN "workTypeId" TEXT;

UPDATE "Order" AS o
SET "workTypeId" = w."id"
FROM "WorkType" AS w
WHERE w."code" = CASE o."type"
    WHEN 'INSTALL' THEN 'install'
    WHEN 'SERVICE' THEN 'service'
    WHEN 'REPAIR'  THEN 'repair'
END;

-- 4. 🔴 Наряд без вида работ не переезжает молча.
--
--    `SET NOT NULL` ниже и сам откатил бы всю миграцию, но сказал бы об этом
--    языком ограничения колонки. Здесь отказ называет причину и число: три
--    значения перечисления перечислены полностью, поэтому непереведённый наряд
--    означает ровно одно — в справочнике нет записи с нужным кодом (её
--    переименовали или удалили до наката). Обнулить вид у настоящих работ с
--    деньгами и адресами нельзя, поэтому накат останавливается.
DO $$
DECLARE orphans integer;
BEGIN
    SELECT count(*) INTO orphans FROM "Order" WHERE "workTypeId" IS NULL;

    IF orphans > 0 THEN
        RAISE EXCEPTION
            'ADR-343: нарядов без вида работ после переноса: %. В справочнике нет записи с кодом install, service или repair — восстановите её и повторите накат. Обнулять вид работ у нарядов миграция не имеет права.',
            orphans;
    END IF;
END $$;

ALTER TABLE "Order" ALTER COLUMN "workTypeId" SET NOT NULL;

ALTER TABLE "Order" DROP COLUMN "type";
DROP TYPE "OrderType";

CREATE INDEX "Order_workTypeId_idx" ON "Order"("workTypeId");

-- 🔴 `RESTRICT`, как у дела календаря: вид работ, на который ссылаются наряды,
--    не удаляют — его отключают. Удаление стёрло бы вид у выполненных работ, а
--    вместе с ним и разбор выручки по видам в сводке месяца.
ALTER TABLE "Order"
    ADD CONSTRAINT "Order_workTypeId_fkey"
    FOREIGN KEY ("workTypeId") REFERENCES "WorkType"("id") ON DELETE RESTRICT ON UPDATE CASCADE;
