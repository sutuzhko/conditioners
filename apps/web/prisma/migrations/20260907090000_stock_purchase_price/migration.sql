-- Закупочная цена позиции склада и её снимок на движении: без них маржа
-- наряда не считается, и утверждение «технику продаём почти в ноль,
-- зарабатываем на монтаже» проверить нечем (ADR-310, CRM §8.2, issue #628).
--
-- Целые рубли, как `Order.price` и `Order.installerFee`: копеек на этом рынке
-- не бывает. Партий и FIFO нет — цена одна на позицию (CRM §11.7).

-- AlterTable
-- 🔴 Без умолчания. Ноль читался бы как «материал достался бесплатно» и
-- завышал бы маржу — то есть врал бы ровно в ту сторону, ради которой поле и
-- заводится. «Цена не заведена» обязано отличаться от «цена равна нулю».
ALTER TABLE "StockItem" ADD COLUMN     "purchasePrice" INTEGER;

-- AlterTable
-- 🔴 Снимок цены на момент движения, а не ссылка на текущую цену позиции.
-- Иначе переоценка трубы сегодня переписывала бы прибыльность каждого наряда
-- за прошлый год, и годовые итоги владельца ехали бы сами. Довод тот же, что
-- у `Order.overtimeMin`: записанный факт прошлого при показе не меняется.
ALTER TABLE "StockMovement" ADD COLUMN     "unitCost" INTEGER;

-- Приведения заведённых строк нет, и это решение, а не пропуск.
--
-- Проставить движениям прошлого текущую цену позиции значило бы выдумать
-- число: по какой цене материал закупался тогда, база не знает — колонки не
-- существовало. Пустая цена честно означает «неизвестно», и маржа наряда с
-- таким движением не показывается вовсе, вместо того чтобы показать
-- правдоподобную неправду.
--
-- 🔴 Существующие строки не задеты ни одним UPDATE: обе колонки добавляются
-- необязательными, поэтому ни одна строка не переписывается и ни одно
-- значение не теряется.
